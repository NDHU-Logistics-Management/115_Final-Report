# ============================================================
# A6　路線改制（1123 → 311／311A）造成平均搭乘里程組成斷點
#
# 背景（2026-09-11 由審查人考證，見 README「路線沿革」）：
#   1123 原為公路客運環狀線（花蓮新站－花蓮總站－花蓮機場－花蓮新站），
#   2023-12-01 移撥為市區公車，統聯客運再自 2024-11-01 起將其拆分改號為
#   311（美崙環線）與 311A（機場線）。
#   因此 1123 並非服務消失，而是同一段服務被重新切分、改號後延續。
#
# 本腳本要證明的問題：
#   1123 不在站間距離表中 → 113/06~113/10 該服務的里程全數為 NA、被排除
#   311／311A 在距離表中  → 113/11 起同一段服務開始計入
#   而 311 是短程環線（全程僅 12.4 km，311A 約 5 km），平均每趟約 4.7 km，
#   遠低於花蓮市區其餘路線的約 17 km。
#
#   結果：113/11 平均搭乘里程的下跌，有一部分純粹是「短程路線由不可計
#   變成可計」的組成效果，而非乘客旅次縮短。報告 §2.1.1 目前將整段跌勢
#   解讀為「平均搭乘距離有逐步縮短之趨勢」。
#
# 本腳本做五件事：
#   1. 以搭乘附屬路線代碼證明 1123 與 311 為同一服務的延續
#   2. 確認 1123 在距離表中無對應資料、311／311A 有
#   3. 計算 311 的路線長度
#   4. 計算含 311 與排除 311 的逐月平均搭乘里程，量化稀釋效果
#   5. 與已交付的 月平均搭乘里程.xlsx 對帳，確認本腳本的簡化演算法可信
#
# 演算法說明：
#   里程計算直接沿用 115期末.Rmd 的 calculate_monthly_mileage()，
#   由 load_mileage_functions() 於執行時從 Rmd 擷取，不另行重寫，
#   以確保結果可與已交付的 月平均搭乘里程.xlsx 對帳（見第 6 節）。
#
# 執行方式：
#   將工作目錄設到本腳本所在資料夾後 source("A6-路線改制里程組成斷點.R")
#   或直接執行 run-all.R
# ============================================================

if (!exists("emit")) source("00-setup.R")


# ------------------------------------------------------------
# 1. 服務延續性：搭乘附屬路線代碼
#
#    若 1123 與 311 共用同一組附屬路線代碼，代表平臺端視為同一條
#    服務線改名，而非兩條不同路線。
# ------------------------------------------------------------

hua <- read_tickets(
  "花蓮縣公車.csv",
  c("搭乘路線名稱", "搭乘附屬路線名稱", "搭乘附屬路線代碼",
    "搭乘公車路線方向", "上車站牌代碼", "上車計費站序資料",
    "下車站牌代碼", "下車站牌站序", "原始票證筆數")
)

hua <- hua[!搭乘路線名稱 %in% hualien_abnormal_routes]

continuity <- hua[
  搭乘路線名稱 %in% c("1123", "311"),
  .(列數 = .N,
    首月 = min(西元年月),
    末月 = max(西元年月)),
  by = .(搭乘路線名稱, 搭乘附屬路線名稱, 搭乘附屬路線代碼)
][order(搭乘附屬路線代碼, 搭乘路線名稱)]

emit(
  continuity,
  "A6-1123與311服務延續性.csv",
  "1123 與 311 的附屬路線代碼對照（共用代碼＝同一服務改號）"
)


# ------------------------------------------------------------
# 2. 距離表覆蓋狀況
# ------------------------------------------------------------

dist <- fread(
  file.path(data_path, "公車站間距離資料", "花蓮縣市區客運站間距離資料.csv"),
  showProgress = FALSE
)
strip_bom(dist)
dist[, 搭乘路線名稱 := trimws(as.character(搭乘路線名稱))]
dist[, 搭乘附屬路線名稱 := trimws(as.character(搭乘附屬路線名稱))]

coverage <- data.table(
  路線 = c("1123", "311", "311A"),
  距離表是否收錄 = c(
    "1123" %in% dist$搭乘路線名稱,
    "311"  %in% dist$搭乘附屬路線名稱,
    "311A" %in% dist$搭乘附屬路線名稱
  )
)

emit(coverage, "A6-距離表覆蓋狀況.csv", "1123／311／311A 在距離表中的收錄狀況")


# ------------------------------------------------------------
# 3. 311 的路線長度
# ------------------------------------------------------------

dist[, 站間距離 := as.numeric(站間距離)]
dist[is.na(站間距離), 站間距離 := 0]

len <- dist[
  搭乘路線名稱 == "311",
  .(站數 = .N, 全程里程_公里 = round(sum(站間距離) / 1000, 2)),
  by = .(搭乘附屬路線名稱, 搭乘公車路線方向)
][order(搭乘附屬路線名稱, 搭乘公車路線方向)]

emit(len, "A6-311路線長度.csv", "311／311A 各方向站數與全程里程")


# ------------------------------------------------------------
# 4. 稀釋效果：含 311 vs 排除 311
# ------------------------------------------------------------

# --- 載入報告本身的配對函數 ---
load_mileage_functions()

# 套用 C1 修正版的站牌代碼正規化。
# 對花蓮市區而言修正前後結果完全相同（HUA 前綴本就有處理），
# 此處改用修正版是為了避免混入 C1 這個獨立問題。
normalize_stop_code <- normalize_stop_code_fixed

idx <- build_distance_index(dist)

res <- calculate_monthly_mileage(in_window(hua), idx)
t   <- res$detail

monthly <- function(x) {
  x[!is.na(里程_公尺),
    .(人次 = sum(原始票證筆數, na.rm = TRUE),
      平均里程 = round(sum(里程_公尺 * 原始票證筆數, na.rm = TRUE) /
                         sum(原始票證筆數, na.rm = TRUE) / 1000, 2)),
    by = .(西元年月 = format(get(DATE_COL), "%Y-%m"),
           民國月份 = 月份)][order(西元年月)]
}

cmp <- merge(
  monthly(t)[, .(西元年月, 民國月份, 全部_人次 = 人次, 全部_里程 = 平均里程)],
  monthly(t[搭乘路線名稱 != "311"])[, .(西元年月, 排除311_里程 = 平均里程)],
  by = "西元年月", all = TRUE
)
cmp <- merge(
  cmp,
  monthly(t[搭乘路線名稱 == "311"])[
    , .(西元年月, `311_人次` = 人次, `311_里程` = 平均里程)],
  by = "西元年月", all = TRUE
)

cmp[, `311占比%` := round(100 * `311_人次` / 全部_人次, 1)]
cmp[, 稀釋效果_公里 := round(全部_里程 - 排除311_里程, 2)]
setorder(cmp, 西元年月)

emit(
  cmp,
  "A6-311稀釋效果.csv",
  "花蓮市區平均搭乘里程：含 311 vs 排除 311"
)


# ------------------------------------------------------------
# 5. 1123 的可配對狀況
# ------------------------------------------------------------

emit(
  t[搭乘路線名稱 == "1123",
    .(列數 = .N,
      人次 = sum(原始票證筆數, na.rm = TRUE),
      可算里程列數 = sum(!is.na(里程_公尺))),
    by = .(民國月份 = 月份)][order(民國月份)],
  "A6-1123可配對狀況.csv",
  "1123 在分析期間內的里程可配對列數（應全為 0）"
)


# ------------------------------------------------------------
# 6. 與已交付結果對帳
# ------------------------------------------------------------

xlsx_path <- file.path(REPO_ROOT, "實作測試", "月平均搭乘里程.xlsx")

if (requireNamespace("openxlsx", quietly = TRUE) && file.exists(xlsx_path)) {

  official <- as.data.table(
    openxlsx::read.xlsx(xlsx_path, sheet = "花蓮市區")
  )
  setnames(official, c("月份", "平均搭乘里程_公里"), c("民國月份", "已交付里程"),
           skip_absent = TRUE)

  recon <- merge(
    cmp[, .(民國月份, 本腳本里程 = 全部_里程)],
    official[, .(民國月份, 已交付里程)],
    by = "民國月份", all = TRUE
  )
  recon[, 差異 := round(本腳本里程 - 已交付里程, 2)]

  emit(recon, "A6-與已交付結果對帳.csv",
       "本腳本簡化演算法 vs 已交付 月平均搭乘里程.xlsx")

  cat("\n最大絕對差異：", max(abs(recon$差異), na.rm = TRUE), "公里\n")

} else {
  cat("\n略過對帳：找不到 openxlsx 套件或 月平均搭乘里程.xlsx\n")
}


cat("\n[A6] 完成。\n")
