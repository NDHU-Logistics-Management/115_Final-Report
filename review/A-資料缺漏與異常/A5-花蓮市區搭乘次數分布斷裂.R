# ============================================================
# A5　花蓮市區 114/11 起搭乘次數分布結構斷裂
#
# 現象：「五次以上」乘客人數自 114/11 起崩跌至 1% 以下，
#       但該月使用人數幾乎未變。報告 §3.1.1 據此得出
#       「高頻使用乘客於後期明顯減少」的結論 ——
#       這是全報告最不利於 TPASS 政策的敘述，必須先確認真偽。
#
# 本腳本做五件事：
#   1. 逐月「每卡當月搭乘次數」分布，定位斷裂點
#   2. 重算搭乘次數區間，複現已交付表格的崩跌
#   3. 分布形狀指標（最大值、P95、高頻卡占比）的時間序列
#   4. 每卡出現天數檢查 —— 判斷是否為卡號雜湊粒度改變所致（與 B2 相關）
#   5. 與臺東市區對照，確認斷裂是否為花蓮獨有
#
# 執行方式：
#   將工作目錄設到本腳本所在資料夾後
#   source("A5-花蓮市區搭乘次數分布斷裂.R")
#   或直接執行 run-all.R
#
# 預期結果（2026-09-10 驗證）：
#   114/10 → 114/11 之間，3 次者 3,011 → 841、5 次者 511 → 51
#   「五次以上」人數 837 → 118，占比 4.5% → 0.7%
#   同期使用人數 18,515 → 17,144，幾乎未變
# ============================================================

if (!exists("emit")) source("00-setup.R")


# ------------------------------------------------------------
# 1. 讀取並套用清理
# ------------------------------------------------------------

hua <- read_tickets(
  "花蓮縣公車.csv",
  c("卡號", "搭乘路線名稱", "原始票證筆數")
)

hua <- in_window(hua[!搭乘路線名稱 %in% hualien_abnormal_routes])
hua <- hua[!is.na(卡號) & 卡號 != ""]

cat("\n花蓮市區（113/06~115/06，已清理）列數：", nrow(hua), "\n")


# ------------------------------------------------------------
# 2. 每卡當月搭乘次數
# ------------------------------------------------------------

pm <- hua[
  , .(搭乘次數 = sum(原始票證筆數, na.rm = TRUE)),
  by = .(西元年月, 民國月份, 卡號)
]

dist_tbl <- dcast(
  pm[搭乘次數 <= 10, .(卡數 = .N), by = .(西元年月, 搭乘次數)],
  西元年月 ~ 搭乘次數,
  value.var = "卡數",
  fill = 0L
)

emit(
  dist_tbl,
  "A5-花蓮市區每卡當月搭乘次數分布.csv",
  "每卡當月搭乘次數分布（1~10 次；觀察 114/11 是否截斷）"
)


# ------------------------------------------------------------
# 3. 搭乘次數區間重算（複現已交付表格）
# ------------------------------------------------------------

pm[, 搭乘次數區間 := fcase(
  搭乘次數 == 1, "僅一次",
  搭乘次數 >= 2 & 搭乘次數 <= 4, "二至四次",
  搭乘次數 >= 5, "五次以上"
)]

freq <- dcast(
  pm[, .(人數 = .N), by = .(西元年月, 民國月份, 搭乘次數區間)],
  西元年月 + 民國月份 ~ 搭乘次數區間,
  value.var = "人數",
  fill = 0L
)

freq[, 使用人數 := 僅一次 + 二至四次 + 五次以上]
freq[, `:=`(
  `僅一次%`   = round(100 * 僅一次 / 使用人數, 1),
  `二至四次%` = round(100 * 二至四次 / 使用人數, 1),
  `五次以上%` = round(100 * 五次以上 / 使用人數, 1)
)]
setorder(freq, 西元年月)

emit(
  freq,
  "A5-花蓮市區搭乘次數區間重算.csv",
  "搭乘次數區間重算（應複現 114/11 起「五次以上」崩跌）"
)


# ------------------------------------------------------------
# 4. 分布形狀指標時間序列
#
#    若為真實行為改變，分布應逐步平移；
#    若為資料產製方式改變，分布上緣會在某月被硬生生截斷。
# ------------------------------------------------------------

shape <- pm[
  , .(
      使用人數     = .N,
      平均搭乘次數 = round(mean(搭乘次數), 3),
      中位數       = as.numeric(median(搭乘次數)),
      P95          = as.numeric(quantile(搭乘次數, 0.95)),
      P99          = as.numeric(quantile(搭乘次數, 0.99)),
      最大值       = max(搭乘次數),
      `5次以上卡數` = sum(搭乘次數 >= 5),
      `10次以上卡數` = sum(搭乘次數 >= 10)
    ),
  by = .(西元年月, 民國月份)
][order(西元年月)]

shape[, 前月最大值 := shift(最大值)]
shape[, 最大值變動 := 最大值 - 前月最大值]

emit(
  shape,
  "A5-花蓮市區分布形狀指標.csv",
  "分布形狀逐月指標（觀察上緣是否被截斷）"
)


# ------------------------------------------------------------
# 5. 每卡出現天數（與 B2 相關）
#
#    若同一卡號在單月內只出現於一天，代表卡號雜湊是「逐日」而非
#    「逐月」—— 此時「每卡當月搭乘次數」實為「每人每日搭乘次數」，
#    分布截斷可能來自雜湊或彙整方式改變，而非乘客行為改變。
# ------------------------------------------------------------

days_per_card <- hua[
  , .(出現天數 = uniqueN(get(DATE_COL))), by = .(西元年月, 卡號)
][
  , .(
      卡數           = .N,
      僅出現1天卡數  = sum(出現天數 == 1),
      `僅出現1天占比%` = round(100 * sum(出現天數 == 1) / .N, 1),
      最多出現天數   = max(出現天數)
    ),
  by = 西元年月
][order(西元年月)]

emit(
  days_per_card,
  "A5-花蓮市區每卡出現天數.csv",
  "每卡單月出現天數（占比 100% 代表卡號為逐日雜湊）"
)


# ------------------------------------------------------------
# 6. 臺東市區對照
#
#    同一期間臺東是否也出現相同斷裂？
#    若否，代表問題屬花蓮資料獨有。
# ------------------------------------------------------------

ttt <- read_tickets(
  "臺東縣公車.csv",
  c("卡號", "搭乘路線名稱", "上車站牌代碼", "原始票證筆數")
)

ttt <- ttt[
  !(get(DATE_COL) %in% taitung_abnormal_dates) |
    搭乘路線名稱 %in% taitung_normal_routes
]
ttt <- in_window(ttt)[!is.na(卡號) & 卡號 != ""]

ttt_pm <- ttt[
  , .(搭乘次數 = sum(原始票證筆數, na.rm = TRUE)),
  by = .(西元年月, 卡號)
]

cmp <- merge(
  shape[, .(西元年月, 民國月份,
            花蓮_使用人數 = 使用人數,
            `花蓮_5次以上%` = round(100 * `5次以上卡數` / 使用人數, 1))],
  ttt_pm[
    , .(臺東_使用人數 = .N,
        `臺東_5次以上%` = round(100 * sum(搭乘次數 >= 5) / .N, 1)),
    by = 西元年月
  ],
  by = "西元年月"
)[order(西元年月)]

emit(
  cmp,
  "A5-花東五次以上占比對照.csv",
  "花蓮 vs 臺東「五次以上」占比逐月對照"
)


cat("\n[A5] 完成。\n")
