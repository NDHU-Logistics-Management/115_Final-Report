# ============================================================
# A3　臺東市區 113/07、114/02 整月每列 `原始票證筆數` 皆為 2
#
# 【2026-09-11 更新】經電話向票證協作平臺確認，`原始票證筆數` 為
#   平臺合併資料時的重複值數量，並非搭乘次數。本項成因即「程式誤將
#   該欄加總」，改以列數（.N）計算後該兩月即恢復正常，無須加註排除。
#   第 1～7 節保留為原始診斷過程；第 8 節為列數基準之重算結果。
#
# 本腳本做五件事：
#   1. 驗證 115期末.Rmd 的臺東清理規則仍完整涵蓋臺北（TPE）污染資料
#   2. 逐月權重稽核，自動標記平均權重偏離 1 的月份
#   3. 以收費價格分布排除「一卡多人」的解釋
#   4. 示範後果 —— 重算搭乘次數區間，證明「僅一次」必然為 0
#   5. 確認哪些指標不受影響（比值型指標分子分母同倍抵銷）
#
# 執行方式：
#   將工作目錄設到本腳本所在資料夾後 source("A3-臺東市區權重異常.R")
#   或直接執行 run-all.R
#
# 預期結果（2026-09-10 驗證）：
#   113/07 共 11,518 列全部權重 2 → 人次 23,036
#   114/02 共 10,101 列幾乎全部權重 2 → 人次 20,278
#   其餘月份平均權重 1.000
#   兩月「僅一次」人數皆為 0（月加總最小值即為 2）
# ============================================================

if (!exists("emit")) source("00-setup.R")


# ------------------------------------------------------------
# 1. 讀取臺東縣公車票證
# ------------------------------------------------------------

ttt_raw <- read_tickets(
  "臺東縣公車.csv",
  c("卡號", "搭乘路線名稱", "上車站牌代碼", "原始票證筆數", "收費價格")
)


# ------------------------------------------------------------
# 2. 清理規則有效性驗證
#
#    115期末.Rmd 以「2026-05-24、2026-05-25 兩日，且路線不在
#    101/201/202/203 之列」排除臺北資料。
#    這裡反向確認：TPE 前綴資料是否恰好都落在那兩天？
#      - TPE 出現在其他日期 → 污染資料殘留
#      - 那兩天有 TTT 資料落在白名單外 → 誤刪臺東正常資料
# ------------------------------------------------------------

ttt_raw[, 站牌前綴 := substr(上車站牌代碼, 1, 3)]

emit(
  ttt_raw[, .(列數 = .N), by = 站牌前綴][order(-列數)],
  "A3-臺東檔站牌代碼前綴分布.csv",
  "臺東縣公車檔的站牌代碼前綴分布（TPE 為臺北資料污染）"
)

tpe_dates <- sort(unique(ttt_raw[站牌前綴 == "TPE"][[DATE_COL]]))
residual  <- setdiff(as.character(tpe_dates), as.character(taitung_abnormal_dates))

on_abn_day <- ttt_raw[
  get(DATE_COL) %in% taitung_abnormal_dates & 站牌前綴 != "TPE"
]
over_deleted <- sort(unique(
  on_abn_day[!搭乘路線名稱 %in% taitung_normal_routes]$搭乘路線名稱
))

rule_check <- data.table(
  檢查項目 = c(
    "TPE 前綴出現的日期",
    "落在清理日期之外的 TPE 資料（污染殘留）",
    "清理日當天被誤刪的臺東路線（誤刪風險）"
  ),
  結果 = c(
    paste(format(tpe_dates), collapse = ", "),
    if (length(residual)) paste(residual, collapse = ", ") else "無",
    if (length(over_deleted)) paste(over_deleted, collapse = ", ") else "無"
  )
)

emit(rule_check, "A3-清理規則有效性驗證.csv", "TPE 清理規則有效性驗證")

if (length(residual) > 0) {
  warning("清理規則已失效：仍有 TPE 資料未被排除 → ", paste(residual, collapse = ", "))
}
if (length(over_deleted) > 0) {
  warning("清理規則誤刪臺東資料 → ", paste(over_deleted, collapse = ", "))
}


# ------------------------------------------------------------
# 3. 套用清理，取得報告實際使用的資料
# ------------------------------------------------------------

ttt <- ttt_raw[
  !(get(DATE_COL) %in% taitung_abnormal_dates) |
    搭乘路線名稱 %in% taitung_normal_routes
]

ttt <- in_window(ttt)

cat("\n原始筆數：", nrow(ttt_raw),
    " 清理並限縮期間後：", nrow(ttt), "\n")


# ------------------------------------------------------------
# 4. 逐月權重稽核
# ------------------------------------------------------------

audit <- weight_audit(ttt)

emit(audit, "A3-臺東市區逐月權重稽核.csv", "臺東市區逐月 原始票證筆數 權重稽核")

emit(
  flag_weight_anomaly(audit),
  "A3-權重異常月份.csv",
  "自動標記：平均權重偏離 1 超過 5% 的月份"
)

emit(
  weight_dist(ttt),
  "A3-權重值月份交叉表.csv",
  "權重值 × 月份 列數交叉表"
)


# ------------------------------------------------------------
# 5. 排除「一卡多人」的解釋
#
#    若權重代表同一次刷卡付多人份，收費價格應同步倍增。
#    比較異常月與鄰月的收費價格分布，若同形即可排除。
# ------------------------------------------------------------

fare <- ttt[
  西元年月 %in% c("2024-06", "2024-07", "2024-08",
                  "2025-01", "2025-02", "2025-03"),
  .(列數 = .N),
  by = .(西元年月, 收費價格)
]

fare[, `占該月%` := round(100 * 列數 / sum(列數), 1), by = 西元年月]

emit(
  dcast(fare, 收費價格 ~ 西元年月, value.var = "占該月%", fill = 0),
  "A3-異常月與鄰月收費價格分布.csv",
  "收費價格分布（%）— 異常月 113/07、114/02 與鄰月對照"
)


# ------------------------------------------------------------
# 6. 後果示範：重算搭乘次數區間
#
#    每位乘客每月使用次數 = sum(原始票證筆數)
#    分類：僅一次 = 1、二至四次 = 2~4、五次以上 >= 5
#    當整月權重皆為 2，月加總最小值即為 2，「僅一次」必然為 0。
# ------------------------------------------------------------

person_month <- ttt[
  !is.na(卡號) & 卡號 != "",
  .(每人每月使用次數 = sum(原始票證筆數, na.rm = TRUE)),
  by = .(西元年月, 民國月份, 卡號)
]

person_month[, 搭乘次數區間 := fcase(
  每人每月使用次數 == 1, "僅一次",
  每人每月使用次數 >= 2 & 每人每月使用次數 <= 4, "二至四次",
  每人每月使用次數 >= 5, "五次以上"
)]

freq <- dcast(
  person_month[, .(人數 = .N), by = .(西元年月, 民國月份, 搭乘次數區間)],
  西元年月 + 民國月份 ~ 搭乘次數區間,
  value.var = "人數",
  fill = 0L
)

freq[, 使用人數 := 僅一次 + 二至四次 + 五次以上]
freq[, `:=`(
  `僅一次%`   = round(100 * 僅一次 / 使用人數, 1),
  `二至四次%` = round(100 * 二至四次 / 使用人數, 1),
  `五次以上%` = round(100 * 五次以上 / 使用人數, 1)
)]
setorder(freq, 西元年月)

emit(
  freq,
  "A3-搭乘次數區間重算結果.csv",
  "搭乘次數區間重算（113/07、114/02 的『僅一次』應為 0）"
)


# ------------------------------------------------------------
# 7. 哪些指標不受影響
#
#    比值型指標的分子分母同倍放大會抵銷，人次型指標則直接失真。
# ------------------------------------------------------------

mileage_note <- data.table(
  指標 = c("平均搭乘里程", "TPASS 使用比例", "平均轉乘次數",
           "該月總使用次數", "平均每日使用次數", "搭乘次數區間"),
  是否受影響 = c("否", "否", "否", "是", "是", "是"),
  理由 = c(
    "比值型，總延人公里與搭乘人次同倍放大而抵銷",
    "比值型，且整月一致放大，分子分母同倍抵銷",
    "程式刻意不以 原始票證筆數 加權（見 115期末.Rmd L4835）",
    "直接等於 sum(原始票證筆數)，整月翻倍",
    "分子為總使用次數，隨之翻倍",
    "每人每月加總翻倍，最小值變 2，『僅一次』歸零"
  )
)

emit(mileage_note, "A3-受影響指標盤點.csv", "各指標是否受本項異常影響")


# ------------------------------------------------------------
# 8. 列數基準重算（2026-09-11 更新）
#
#    `原始票證筆數` 為平臺端重複值數量，非搭乘次數。
#    正確做法：一列算一次（.N）。本節以列數重算受影響指標，
#    與加總基準並列，證明改正後 113/07、114/02 即恢復正常。
# ------------------------------------------------------------

days_in <- function(ym) {
  d1 <- as.Date(paste0(ym, "-01"))
  as.integer(format(seq(d1, by = "month", length.out = 2)[2] - 1, "%d"))
}

daily_n <- ttt[
  !is.na(卡號) & 卡號 != "",
  .(總使用次數_列數 = .N,
    總使用次數_加總 = sum(原始票證筆數, na.rm = TRUE),
    使用人數 = uniqueN(卡號)),
  by = .(西元年月, 民國月份)
][order(西元年月)]

daily_n[, 該月天數 := sapply(西元年月, days_in)]
daily_n[, `:=`(
  平均每日_列數基準 = round(總使用次數_列數 / 使用人數 / 該月天數, 3),
  平均每日_加總基準 = round(總使用次數_加總 / 使用人數 / 該月天數, 3)
)]

emit(
  daily_n,
  "A3-列數基準_平均每日使用次數.csv",
  "平均每日使用次數：列數基準（正確）vs 加總基準（現行）"
)

pm_n <- ttt[
  !is.na(卡號) & 卡號 != "",
  .(次數 = .N),
  by = .(西元年月, 民國月份, 卡號)
]
pm_n[, 區間 := fcase(
  次數 == 1, "僅一次",
  次數 >= 2 & 次數 <= 4, "二至四次",
  次數 >= 5, "五次以上"
)]

freq_n <- dcast(
  pm_n[, .(人數 = .N), by = .(西元年月, 民國月份, 區間)],
  西元年月 + 民國月份 ~ 區間,
  value.var = "人數",
  fill = 0L
)
freq_n[, 使用人數 := 僅一次 + 二至四次 + 五次以上]
freq_n[, `:=`(
  `僅一次%`   = round(100 * 僅一次 / 使用人數, 1),
  `二至四次%` = round(100 * 二至四次 / 使用人數, 1),
  `五次以上%` = round(100 * 五次以上 / 使用人數, 1)
)]
setorder(freq_n, 西元年月)

emit(
  freq_n,
  "A3-列數基準_搭乘次數區間.csv",
  "搭乘次數區間（列數基準，正確版；113/07、114/02 應恢復正常）"
)


cat("\n[A3] 完成。\n")
