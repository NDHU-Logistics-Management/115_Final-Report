# ============================================================
# A3／A4 補充　`原始票證筆數` 非 1 值在四份資料的分布（資料集 × 業者 × 月份）
#
# 問題：`原始票證筆數` 於許多「業者－月份」組合固定為 1 或 2，非 1 的值又
#       主要為 4、8、16 等 2 的次方。這些非 1 的月份究竟出現在
#       公路客運檔、臺東市區檔還是花蓮市區檔？
#
# 本腳本做三件事：
#   1. 四份報告用資料（臺東公路、花蓮公路、臺東市區、花蓮市區）加上
#      公路客運全檔，逐月統計 `原始票證筆數` 的值分布（1／2／4／8／16／其他）
#   2. 細到「業者 × 月份」，標記每個組合的型態
#        全為1        ：非 1 占比 = 0
#        零星2        ：僅含 2，且非 1 占比 ≤ 5%
#        整月為2      ：值 2 占比 ≥ 95%（A3 型態）
#        含2的次方≥4  ：出現 4／8／16（A4 型態）
#        其他
#   3. 彙整成資料集層級摘要，直接回答「非 1 的月份出現在哪一份資料」
#
# 清理規則與 A3、A4 相同（臺北污染兩日、花蓮 HSZ 路線），
# 稽核對象即報告實際使用的資料。
#
# 執行方式：
#   將工作目錄設到本腳本所在資料夾後
#   source("A3A4-原始票證筆數跨資料集業者月份分布.R", encoding = "UTF-8")
# ============================================================

if (!exists("emit")) source("00-setup.R")

W <- "原始票證筆數"
COLS <- c("業者編號", "搭乘路線名稱", W)


# ------------------------------------------------------------
# 1. 讀取四份資料並套用報告的清理規則
# ------------------------------------------------------------

thb <- in_window(read_tickets("公路客運2024_to_202606.csv", COLS))
ttt <- read_tickets("臺東縣公車.csv", COLS)
hua <- read_tickets("花蓮縣公車.csv", COLS)

ttt <- in_window(ttt[
  !(get(DATE_COL) %in% taitung_abnormal_dates) |
    搭乘路線名稱 %in% taitung_normal_routes
])
hua <- in_window(hua[!搭乘路線名稱 %in% hualien_abnormal_routes])

datasets <- list(
  `公路客運（全檔）` = thb,
  `臺東公路`         = thb[搭乘路線名稱 %in% routes_taitung_THB],
  `花蓮公路`         = thb[搭乘路線名稱 %in% routes_hualien_THB],
  `臺東市區`         = ttt,
  `花蓮市區`         = hua
)

all <- rbindlist(
  lapply(names(datasets), function(nm) {
    d <- datasets[[nm]][, c("業者編號", "西元年月", "民國月份", W), with = FALSE]
    d[, 資料集 := nm]
    d
  }),
  use.names = TRUE
)
all[, 資料集 := factor(資料集, levels = names(datasets))]
all[, 值 := get(W)]

cat("\n各資料集列數：\n")
print(all[, .N, by = 資料集])


# ------------------------------------------------------------
# 2. 值分布統計函數（可套用於任意分組）
# ------------------------------------------------------------

value_profile <- function(d, by) {
  out <- d[
    ,
    .(
      列數   = .N,
      值1    = sum(值 == 1L, na.rm = TRUE),
      值2    = sum(值 == 2L, na.rm = TRUE),
      值4    = sum(值 == 4L, na.rm = TRUE),
      值8    = sum(值 == 8L, na.rm = TRUE),
      值16   = sum(值 == 16L, na.rm = TRUE),
      其他值 = sum(!值 %in% c(1L, 2L, 4L, 8L, 16L), na.rm = TRUE),
      其他值清單 = {
        v <- sort(unique(值[!值 %in% c(1L, 2L, 4L, 8L, 16L)]))
        if (length(v)) paste(v, collapse = "/") else ""
      },
      平均值 = round(mean(值, na.rm = TRUE), 3)
    ),
    by = by
  ]
  out[, `非1占比%` := round(100 * (列數 - 值1) / 列數, 1)]
  out[, `值2占比%` := round(100 * 值2 / 列數, 1)]
  out[, `≥4占比%`  := round(100 * (值4 + 值8 + 值16) / 列數, 1)]
  out[, 型態 := fcase(
    列數 - 值1 == 0,                       "全為1",
    值4 + 值8 + 值16 > 0,                  "含2的次方≥4",
    值2 / 列數 >= 0.95,                    "整月為2",
    其他值 == 0 & (列數 - 值1) / 列數 <= 0.05, "零星2",
    default = "其他"
  )]
  out[]
}


# ------------------------------------------------------------
# 3. 資料集 × 月份
# ------------------------------------------------------------

by_month <- value_profile(all, by = c("資料集", "西元年月", "民國月份"))
setorder(by_month, 資料集, 西元年月)

emit(
  by_month,
  "A3A4-原始票證筆數_資料集月份值分布.csv",
  "原始票證筆數 值分布：資料集 × 月份"
)

emit(
  by_month[型態 != "全為1" & `非1占比%` > 5],
  "A3A4-原始票證筆數_非1占比逾5%月份.csv",
  "非 1 占比超過 5% 的（資料集，月份）"
)


# ------------------------------------------------------------
# 4. 資料集 × 業者 × 月份
# ------------------------------------------------------------

by_op_month <- value_profile(all, by = c("資料集", "業者編號", "西元年月", "民國月份"))
setorder(by_op_month, 資料集, 業者編號, 西元年月)

emit(
  by_op_month,
  "A3A4-原始票證筆數_業者月份值分布.csv",
  "原始票證筆數 值分布：資料集 × 業者 × 月份（全部組合）"
)

emit(
  by_op_month[型態 %in% c("整月為2", "含2的次方≥4", "其他")],
  "A3A4-原始票證筆數_業者月份異常組合.csv",
  "業者－月份 異常組合（整月為2／含2的次方≥4／其他）"
)

# 型態 × 資料集 的組合數
pattern_ct <- dcast(
  by_op_month[, .(組合數 = .N), by = .(資料集, 型態)],
  資料集 ~ 型態, value.var = "組合數", fill = 0L
)

emit(
  pattern_ct,
  "A3A4-原始票證筆數_業者月份型態計數.csv",
  "各資料集的 業者－月份 組合型態計數"
)


# ------------------------------------------------------------
# 5. 資料集層級摘要
# ------------------------------------------------------------

summary_ds <- by_month[
  ,
  .(
    月份數            = .N,
    有非1的月份數     = sum(`非1占比%` > 0),
    `非1逾5%的月份數` = sum(`非1占比%` > 5),
    整月為2的月份數   = sum(型態 == "整月為2"),
    `含≥4的月份數`    = sum(值4 + 值8 + 值16 > 0),
    出現的值          = {
      v <- c(if (sum(值1)) 1, if (sum(值2)) 2, if (sum(值4)) 4,
             if (sum(值8)) 8, if (sum(值16)) 16)
      o <- unique(unlist(strsplit(其他值清單[其他值清單 != ""], "/")))
      paste(c(v, o), collapse = "/")
    },
    非1列數           = sum(列數 - 值1),
    總列數            = sum(列數)
  ),
  by = 資料集
]
summary_ds[, `非1列占比%` := round(100 * 非1列數 / 總列數, 2)]

op_sum <- by_op_month[
  ,
  .(
    業者月份組合數       = .N,
    整月為2組合數        = sum(型態 == "整月為2"),
    `含≥4組合數`         = sum(型態 == "含2的次方≥4"),
    涉及業者             = paste(sort(unique(業者編號[型態 %in% c("整月為2", "含2的次方≥4")])),
                                collapse = "/"),
    涉及月份             = paste(sort(unique(民國月份[型態 %in% c("整月為2", "含2的次方≥4")])),
                                collapse = "/")
  ),
  by = 資料集
]

summary_ds <- merge(summary_ds, op_sum, by = "資料集", sort = FALSE)

emit(
  summary_ds,
  "A3A4-原始票證筆數_資料集摘要.csv",
  "資料集層級摘要：非 1 值出現在哪一份資料"
)


# ------------------------------------------------------------
# 6. 非 1 列的絕對量歸屬（回答「主要出現在哪份資料」）
# ------------------------------------------------------------

share <- all[資料集 != "公路客運（全檔）" & 值 != 1,
             .(非1列數 = .N,
               值2 = sum(值 == 2L), `值≥4` = sum(值 >= 4L)),
             by = 資料集]
share[, `占四份資料非1列%` := round(100 * 非1列數 / sum(非1列數), 1)]

emit(
  share,
  "A3A4-原始票證筆數_非1列歸屬.csv",
  "四份報告用資料中，非 1 列的絕對量與占比"
)

cat("\n[A3A4] 完成。\n")
