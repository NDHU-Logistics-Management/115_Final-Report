# ============================================================
# A1　臺東縣公路客運 114/11 整月缺少東台灣客運（0816）
#
# 本腳本做三件事：
#   1. 通用偵測 —— 找出所有「首末月之間出現整月斷檔」的業者。
#      不預設答案，任何業者的缺漏都會被列出。
#   2. 量化該缺漏對臺東公路月資料量的影響。
#   3. 以日為單位確認斷點邊界，證明是整月中斷而非零星短缺。
#
# 執行方式：
#   將工作目錄設到本腳本所在資料夾後 source("A1-臺東公路業者資料覆蓋.R")
#   或直接執行 run-all.R
#
# 預期結果（2026-09-10 驗證）：
#   0816 於 2025-11 整月 0 筆，前月 50,646、後月 52,425
#   同期 1201 有 22,279 筆、1602 有 34,284 筆，非全體資料集問題
#   0816 佔臺東公路約 45%，缺漏使該月人次僅剩鄰月一半
# ============================================================

if (!exists("emit")) source("00-setup.R")


# ------------------------------------------------------------
# 1. 讀取公路客運票證
# ------------------------------------------------------------

thb <- read_tickets(
  "公路客運2024_to_202606.csv",
  c("業者編號", "搭乘路線名稱", "原始票證筆數")
)


# ------------------------------------------------------------
# 2. 業者 × 月份覆蓋表（全檔，不限縣市）
# ------------------------------------------------------------

by_op <- thb[
  ,
  .(列數 = .N, 人次 = sum(原始票證筆數, na.rm = TRUE)),
  by = .(業者編號, 西元年月)
][order(業者編號, 西元年月)]

cover_wide <- dcast(
  by_op,
  業者編號 ~ 西元年月,
  value.var = "列數",
  fill = 0L
)

emit(
  cover_wide,
  "A1-公路客運業者月覆蓋表.csv",
  "業者 × 月份 列數（0 代表該月完全無資料）"
)


# ------------------------------------------------------------
# 3. 通用斷檔偵測
#
#    對每個業者，取其首次與末次出現的月份，
#    檢查中間是否有整月為 0 的情形。
#    這種「中間空、兩端有」的形態才是資料缺漏；
#    末端消失可能是停業或路線移轉，另行標記。
# ------------------------------------------------------------

all_months <- sort(unique(thb$西元年月))

gaps <- by_op[
  ,
  {
    first_m <- min(西元年月)
    last_m  <- max(西元年月)
    span    <- all_months[all_months >= first_m & all_months <= last_m]
    missing <- setdiff(span, 西元年月)

    if (length(missing) > 0) {
      .(斷檔月份 = missing, 首次出現 = first_m, 末次出現 = last_m)
    } else {
      .(斷檔月份 = character(0), 首次出現 = character(0), 末次出現 = character(0))
    }
  },
  by = 業者編號
]

# 補上斷檔前後月的資料量，方便判斷嚴重程度
if (nrow(gaps) > 0) {
  gaps[, `:=`(
    前月 = all_months[match(斷檔月份, all_months) - 1L],
    後月 = all_months[match(斷檔月份, all_months) + 1L]
  )]
  gaps <- merge(
    gaps, by_op[, .(業者編號, 前月 = 西元年月, 前月列數 = 列數)],
    by = c("業者編號", "前月"), all.x = TRUE, sort = FALSE
  )
  gaps <- merge(
    gaps, by_op[, .(業者編號, 後月 = 西元年月, 後月列數 = 列數)],
    by = c("業者編號", "後月"), all.x = TRUE, sort = FALSE
  )
  setcolorder(gaps, c("業者編號", "斷檔月份", "前月", "前月列數",
                      "後月", "後月列數", "首次出現", "末次出現"))
  setorder(gaps, 業者編號, 斷檔月份)
}

emit(
  gaps,
  "A1-業者整月斷檔偵測.csv",
  "整月斷檔偵測（首末月之間出現 0 筆的業者）"
)

# 末端消失的業者（可能為停業或移轉，非本項但一併標記）
tail_stop <- by_op[
  , .(末次出現 = max(西元年月)), by = 業者編號
][末次出現 < max(all_months)]

emit(
  tail_stop,
  "A1-業者末端停止供料.csv",
  "資料在期末前即停止的業者（需確認為停業或缺漏）"
)


# ------------------------------------------------------------
# 4. 缺漏對臺東公路的影響
# ------------------------------------------------------------

ttt <- thb[搭乘路線名稱 %in% routes_taitung_THB]

ttt_month <- ttt[
  ,
  .(列數 = .N, 人次 = sum(原始票證筆數, na.rm = TRUE)),
  by = .(西元年月, 民國月份)
][order(西元年月)]

ttt_0816 <- ttt[
  業者編號 == "0816",
  .(x0816列數 = .N),
  by = 西元年月
]

ttt_month <- merge(ttt_month, ttt_0816, by = "西元年月", all.x = TRUE)
ttt_month[is.na(x0816列數), x0816列數 := 0L]
ttt_month[, `0816占比%` := round(100 * x0816列數 / 列數, 1)]
setnames(ttt_month, "x0816列數", "0816列數")

emit(
  ttt_month,
  "A1-臺東公路月資料量與0816占比.csv",
  "臺東公路逐月資料量與 0816 占比"
)


# ------------------------------------------------------------
# 5. 斷點邊界：以日為單位
# ------------------------------------------------------------

daily <- thb[
  業者編號 == "0816" &
    get(DATE_COL) >= as.Date("2025-10-25") &
    get(DATE_COL) <= as.Date("2025-12-05"),
  .(列數 = .N),
  by = .(日期 = get(DATE_COL))
][order(日期)]

emit(
  daily,
  "A1-0816斷點前後每日筆數.csv",
  "0816 於 2025-10-25 ~ 2025-12-05 每日筆數（缺漏日不會出現在表中）"
)


# ------------------------------------------------------------
# 6. 同期其他業者對照
# ------------------------------------------------------------

peer <- by_op[
  西元年月 %in% c("2025-10", "2025-11", "2025-12")
][order(業者編號, 西元年月)]

emit(
  peer,
  "A1-2025年11月前後各業者對照.csv",
  "2025-10 ~ 2025-12 各業者資料量對照"
)


cat("\n[A1] 完成。\n")
