# ------------------------------------------------------------
# 8. 列數基準重算（2026-09-11 更新）
#
#    `原始票證筆數` 為平臺端重複值數量，非搭乘次數。
#    正確做法：一列算一次（.N）。本節以列數重算受影響指標，
#    與加總基準並列，證明改正後 115/04 即恢復正常。
# ------------------------------------------------------------

days_in <- function(ym) {
  d1 <- as.Date(paste0(ym, "-01"))
  as.integer(format(seq(d1, by = "month", length.out = 2)[2] - 1, "%d"))
}

recount_daily <- function(d) {
  x <- d[
    !is.na(卡號) & 卡號 != "",
    .(總使用次數_列數 = .N,
      總使用次數_加總 = sum(原始票證筆數, na.rm = TRUE),
      使用人數 = uniqueN(卡號)),
    by = .(西元年月, 民國月份)
  ][order(西元年月)]
  x[, 該月天數 := sapply(西元年月, days_in)]
  x[, `:=`(
    平均每日_列數基準 = round(總使用次數_列數 / 使用人數 / 該月天數, 3),
    平均每日_加總基準 = round(總使用次數_加總 / 使用人數 / 該月天數, 3)
  )][]
}

recount_freq <- function(d) {
  pm <- d[!is.na(卡號) & 卡號 != "", .(次數 = .N), by = .(西元年月, 民國月份, 卡號)]
  pm[, 區間 := fcase(
    次數 == 1, "僅一次",
    次數 >= 2 & 次數 <= 4, "二至四次",
    次數 >= 5, "五次以上"
  )]
  f <- dcast(
    pm[, .(人數 = .N), by = .(西元年月, 民國月份, 區間)],
    西元年月 + 民國月份 ~ 區間, value.var = "人數", fill = 0L
  )
  f[, 使用人數 := 僅一次 + 二至四次 + 五次以上]
  f[, `:=`(
    `僅一次%`   = round(100 * 僅一次 / 使用人數, 1),
    `二至四次%` = round(100 * 二至四次 / 使用人數, 1),
    `五次以上%` = round(100 * 五次以上 / 使用人數, 1)
  )]
  setorder(f, 西元年月)
  f[]
}

emit(
  recount_daily(hua_thb),
  "A4-列數基準_花蓮公路平均每日使用次數.csv",
  "花蓮公路 平均每日使用次數：列數基準（正確）vs 加總基準（現行）"
)

emit(
  recount_freq(hua_thb),
  "A4-列數基準_花蓮公路搭乘次數區間.csv",
  "花蓮公路 搭乘次數區間（列數基準，正確版；115/04 應恢復正常）"
)

