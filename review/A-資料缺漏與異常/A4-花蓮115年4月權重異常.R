# ============================================================
# A4　花蓮公路／市區 115/04 權重異常（4、8、16）
#
# 【2026-09-11 更新】經電話向票證協作平臺確認，`原始票證筆數` 為
#   平臺合併資料時的重複值數量，並非搭乘次數。本項成因即「程式誤將
#   該欄加總」，改以列數（.N）計算後 115/04 即恢復正常，無須加註排除。
#   第 1～7 節保留為原始診斷過程；第 8 節為列數基準之重算結果。
#
# 本腳本做六件事：
#   1. 花蓮公路逐月權重稽核，自動標記異常月份
#   2. 權重值 × 月份交叉表，顯示 4／8／16 這組 2 的次方形態
#   3. 異常列在月內的日期分布，確認是否集中於特定期間
#   4. 異常列的路線分布，確認是否跨路線一致（排除單一路線活動）
#   5. TPASS 與非 TPASS 的權重是否對稱，評估比值型指標是否也失真
#   6. 花蓮市區同月是否有相同形態，判斷是否為同一批交付檔的問題
#
# 執行方式：
#   將工作目錄設到本腳本所在資料夾後 source("A4-花蓮115年4月權重異常.R")
#   或直接執行 run-all.R
#
# 預期結果（2026-09-10 驗證）：
#   花蓮公路 115/04：34,305 列 → 56,491 人次，虛增 22,186（+65%）
#   鄰月 115/03、115/05 虛增僅約 +3%
#   權重值為 4、8、16；集中於 2026-04-22 ~ 04-28 連續七天
#   （該七日 78~83% 的列權重 >= 4，前後日期僅 0~0.7%）
#   跨路線一致，非單一路線活動
#   TPASS 平均權重 1.666 vs 其他票種 1.642 → 接近對稱，
#   TPASS 比例僅偏高 0.24 個百分點，實質影響可忽略
#   花蓮市區同月亦有 1,964 列權重 4（虛增 5,892 人次）
# ============================================================

if (!exists("emit")) source("00-setup.R")

TPASS_TYPES <- c("#HUA-199", "#HUA-399", "#TTT-299")


# ------------------------------------------------------------
# 1. 花蓮公路：讀取並套用路線篩選
# ------------------------------------------------------------

thb <- read_tickets(
  "公路客運2024_to_202606.csv",
  c("業者編號", "卡號", "搭乘路線名稱", "票種次類型", "原始票證筆數")
)

hua_thb <- in_window(thb[搭乘路線名稱 %in% routes_hualien_THB])

cat("\n花蓮公路（113/06~115/06）列數：", nrow(hua_thb), "\n")


# ------------------------------------------------------------
# 2. 逐月權重稽核
# ------------------------------------------------------------

audit <- weight_audit(hua_thb)

emit(audit, "A4-花蓮公路逐月權重稽核.csv", "花蓮公路逐月 原始票證筆數 權重稽核")

emit(
  flag_weight_anomaly(audit),
  "A4-花蓮公路權重異常月份.csv",
  "自動標記：平均權重偏離 1 超過 5% 的月份"
)

emit(
  weight_dist(hua_thb),
  "A4-花蓮公路權重值月份交叉表.csv",
  "權重值 × 月份 列數交叉表（正常應僅有 1、偶有 2）"
)


# ------------------------------------------------------------
# 3. 異常列的日期分布
#
#    若為真實搭乘行為，異常應散布全月；
#    若集中於連續數日，較可能是特定批次的處理故障。
# ------------------------------------------------------------

apr <- hua_thb[西元年月 == "2026-04"]

daily <- apr[
  , .(
      總列數     = .N,
      權重4以上  = sum(原始票證筆數 >= 4, na.rm = TRUE),
      人次       = sum(原始票證筆數, na.rm = TRUE)
    ),
  by = .(日期 = get(DATE_COL))
][order(日期)]

daily[, `:=`(
  虛增人次 = 人次 - 總列數,
  `權重4以上占比%` = round(100 * 權重4以上 / 總列數, 1)
)]

emit(
  daily,
  "A4-花蓮公路2026年4月每日權重分布.csv",
  "2026-04 每日列數與高權重列占比"
)


# ------------------------------------------------------------
# 4. 異常列的路線分布
#
#    比較「高權重列」與「權重 1 列」在各路線的占比。
#    若兩者比例接近，代表異常跨路線一致，非單一路線的真實事件。
# ------------------------------------------------------------

route_cmp <- merge(
  apr[原始票證筆數 >= 4, .(高權重列數 = .N), by = 搭乘路線名稱],
  apr[原始票證筆數 == 1, .(權重1列數 = .N), by = 搭乘路線名稱],
  by = "搭乘路線名稱", all = TRUE
)

route_cmp[is.na(高權重列數), 高權重列數 := 0L]
route_cmp[is.na(權重1列數), 權重1列數 := 0L]
route_cmp[, `高權重占該路線%` :=
            round(100 * 高權重列數 / (高權重列數 + 權重1列數), 1)]
setorder(route_cmp, -高權重列數)

emit(
  route_cmp,
  "A4-花蓮公路2026年4月異常列路線分布.csv",
  "高權重列 vs 權重1列 的路線分布（占比接近代表跨路線一致）"
)


# ------------------------------------------------------------
# 5. TPASS 與非 TPASS 的權重對稱性
#
#    比值型指標（如 TPASS 使用比例）唯有在分子分母同倍放大時
#    才會抵銷。若兩者平均權重不同，該比例也會失真。
# ------------------------------------------------------------

sym <- hua_thb[
  西元年月 %in% c("2026-03", "2026-04", "2026-05"),
  .(
    列數     = .N,
    人次     = sum(原始票證筆數, na.rm = TRUE),
    平均權重 = round(mean(原始票證筆數, na.rm = TRUE), 3)
  ),
  by = .(西元年月,
         票種分類 = fifelse(票種次類型 %in% TPASS_TYPES, "TPASS", "其他票種"))
][order(西元年月, 票種分類)]

emit(
  sym,
  "A4-花蓮公路TPASS權重對稱性.csv",
  "TPASS vs 其他票種 平均權重（差異代表 TPASS 比例亦失真）"
)

ratio_cmp <- hua_thb[
  西元年月 %in% c("2026-03", "2026-04", "2026-05"),
  .(
    `依人次TPASS比例%` = round(
      100 * sum(原始票證筆數[票種次類型 %in% TPASS_TYPES], na.rm = TRUE) /
        sum(原始票證筆數, na.rm = TRUE), 2),
    `依列數TPASS比例%` = round(
      100 * sum(票種次類型 %in% TPASS_TYPES) / .N, 2)
  ),
  by = 西元年月
][order(西元年月)]

ratio_cmp[, 差距百分點 := round(`依人次TPASS比例%` - `依列數TPASS比例%`, 2)]

emit(
  ratio_cmp,
  "A4-花蓮公路TPASS比例權重敏感度.csv",
  "以人次 vs 以列數計算的 TPASS 比例（差距大代表受權重異常影響）"
)


