# ============================================================
# A2　花蓮縣市區客運 2026-04-10 起缺少太魯閣客運（0412）
#
# 本腳本做四件事：
#   1. 驗證 115期末.Rmd 的 HSZ 清理規則仍完整涵蓋外縣市污染資料
#      （若來源端新增 HSZ 路線，黑名單會失效而無人察覺）
#   2. 通用偵測 —— 找出資料在期末前即停止的業者與路線
#   3. 以日為單位定位 0412 的中斷點
#   4. 量化缺漏對花蓮市區月資料量的影響
#
# 執行方式：
#   將工作目錄設到本腳本所在資料夾後 source("A2-花蓮市區業者資料覆蓋.R")
#   或直接執行 run-all.R
#
# 預期結果（2026-09-10 驗證）：
#   0412 最後一筆為 2026-04-09，2026-05、2026-06 完全無資料
#   受影響路線 301、302、303、305；301 占花蓮市區全期約 46%
#   同期 1201、1602 及路線 308/309/310/311 資料完整至 2026-06-30
# ============================================================

if (!exists("emit")) source("00-setup.R")


# ------------------------------------------------------------
# 1. 讀取花蓮縣公車票證
# ------------------------------------------------------------

hua_raw <- read_tickets(
  "花蓮縣公車.csv",
  c("業者編號", "搭乘路線名稱", "上車站牌代碼", "原始票證筆數")
)

cat("\n檔案日期範圍：",
    format(min(hua_raw[[DATE_COL]])), "~",
    format(max(hua_raw[[DATE_COL]])), "\n")


# ------------------------------------------------------------
# 2. 清理規則有效性驗證
#
#    115期末.Rmd 以「路線名稱黑名單」排除新竹（HSZ）資料。
#    這裡反向確認：黑名單是否恰好等於所有 HSZ 前綴的路線？
#      - 有 HSZ 前綴卻不在黑名單 → 污染資料殘留
#      - 在黑名單卻無 HSZ 前綴   → 誤刪花蓮正常資料
# ------------------------------------------------------------

hua_raw[, 站牌前綴 := substr(上車站牌代碼, 1, 3)]

prefix_summary <- hua_raw[
  , .(列數 = .N), by = 站牌前綴
][order(-列數)]

emit(
  prefix_summary,
  "A2-花蓮檔站牌代碼前綴分布.csv",
  "花蓮縣公車檔的站牌代碼前綴分布（HSZ 為新竹資料污染）"
)

foreign_routes  <- sort(unique(hua_raw[站牌前綴 == "HSZ"]$搭乘路線名稱))
residual        <- setdiff(foreign_routes, hualien_abnormal_routes)
over_deleted    <- sort(unique(
  hua_raw[搭乘路線名稱 %in% hualien_abnormal_routes & 站牌前綴 != "HSZ"]$搭乘路線名稱
))

rule_check <- data.table(
  檢查項目 = c(
    "HSZ 前綴實際出現的路線",
    "黑名單漏掉的 HSZ 路線（污染殘留）",
    "黑名單誤刪的非 HSZ 路線（誤刪風險）"
  ),
  結果 = c(
    paste(foreign_routes, collapse = ", "),
    if (length(residual)) paste(residual, collapse = ", ") else "無",
    if (length(over_deleted)) paste(over_deleted, collapse = ", ") else "無"
  )
)

emit(
  rule_check,
  "A2-清理規則有效性驗證.csv",
  "HSZ 清理黑名單有效性驗證"
)

if (length(residual) > 0) {
  warning("清理黑名單已失效：仍有 HSZ 路線未被排除 → ",
          paste(residual, collapse = ", "))
}
if (length(over_deleted) > 0) {
  warning("清理黑名單誤刪花蓮資料 → ", paste(over_deleted, collapse = ", "))
}


# ------------------------------------------------------------
# 3. 套用清理，取得報告實際使用的資料
# ------------------------------------------------------------

hua <- hua_raw[!搭乘路線名稱 %in% hualien_abnormal_routes]

cat("\n原始筆數：", nrow(hua_raw),
    " 清理後：", nrow(hua),
    " 排除：", nrow(hua_raw) - nrow(hua), "\n")


# ------------------------------------------------------------
# 4. 業者 × 月份覆蓋表
# ------------------------------------------------------------

by_op <- hua[
  , .(列數 = .N, 人次 = sum(原始票證筆數, na.rm = TRUE)),
  by = .(業者編號, 西元年月)
][order(業者編號, 西元年月)]

emit(
  dcast(by_op, 業者編號 ~ 西元年月, value.var = "列數", fill = 0L),
  "A2-花蓮市區業者月覆蓋表.csv",
  "業者 × 月份 列數（0 代表該月完全無資料）"
)


# ------------------------------------------------------------
# 5. 通用偵測：資料在期末前即停止的業者與路線
# ------------------------------------------------------------

file_last_month <- max(hua$西元年月)

op_stop <- hua[
  , .(首次出現 = min(西元年月),
      末次出現 = max(西元年月),
      最後一筆 = max(get(DATE_COL)),
      總列數   = .N),
  by = 業者編號
][末次出現 < file_last_month][order(末次出現)]

emit(
  op_stop,
  "A2-提前停止供料的業者.csv",
  paste0("資料未涵蓋至 ", file_last_month, " 的業者")
)

route_stop <- hua[
  , .(首次出現 = min(西元年月),
      末次出現 = max(西元年月),
      最後一筆 = max(get(DATE_COL)),
      總列數   = .N),
  by = 搭乘路線名稱
][末次出現 < file_last_month][order(末次出現)]

route_stop[, `占全期比重%` := round(100 * 總列數 / nrow(hua), 2)]

emit(
  route_stop,
  "A2-提前停止供料的路線.csv",
  paste0("資料未涵蓋至 ", file_last_month, " 的路線")
)


# ------------------------------------------------------------
# 6. 斷點定位：0412 於 2026-03 ~ 2026-04 每日筆數
# ------------------------------------------------------------

daily <- hua[
  業者編號 == "0412" & 西元年月 %in% c("2026-03", "2026-04"),
  .(列數 = .N),
  by = .(日期 = get(DATE_COL))
][order(日期)]

emit(
  daily,
  "A2-0412斷點前後每日筆數.csv",
  "0412 於 2026-03 ~ 2026-04 每日筆數（缺漏日不會出現在表中）"
)

cat("\n0412 最後一筆日期：", format(max(daily$日期)), "\n")
cat("同期全檔最後一筆日期：", format(max(hua[[DATE_COL]])), "\n")


# ------------------------------------------------------------
# 7. 缺漏對花蓮市區的影響
# ------------------------------------------------------------

month_total <- hua[
  , .(列數 = .N, 人次 = sum(原始票證筆數, na.rm = TRUE)),
  by = .(西元年月, 民國月份)
][order(西元年月)]

m0412 <- hua[業者編號 == "0412", .(x0412列數 = .N), by = 西元年月]

month_total <- merge(month_total, m0412, by = "西元年月", all.x = TRUE)
month_total[is.na(x0412列數), x0412列數 := 0L]
month_total[, `0412占比%` := round(100 * x0412列數 / 列數, 1)]
setnames(month_total, "x0412列數", "0412列數")

emit(
  month_total,
  "A2-花蓮市區月資料量與0412占比.csv",
  "花蓮市區逐月資料量與 0412 占比"
)


# ------------------------------------------------------------
# 8. 路線 × 月份（確認 301/302/303/305 消失、308-311 續存）
# ------------------------------------------------------------

emit(
  dcast(
    hua[, .(列數 = .N), by = .(搭乘路線名稱, 西元年月)],
    搭乘路線名稱 ~ 西元年月,
    value.var = "列數",
    fill = 0L
  ),
  "A2-花蓮市區路線月覆蓋表.csv",
  "路線 × 月份 列數"
)


cat("\n[A2] 完成。\n")
