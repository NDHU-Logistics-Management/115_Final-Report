# 異常值旗標到底標了什麼？旗標為 1 的列，其站序與時間欄位長什麼樣
suppressPackageStartupMessages(library(data.table))
options(width = 200)
p <- "d:/Github/115_Final-Report/data/臺東縣公車.csv"
cat("欄位 26 全名：", names(fread(p, nrows = 0))[26], "\n\n")

d <- fread(p, select = c(13, 15, 16, 17, 19, 20, 26, 30),
           colClasses = list(character = c(1, 4, 7)), showProgress = FALSE)
setnames(d, c("上車站牌", "上車站序", "上車時間", "下車站牌", "下車站序", "下車時間", "旗標", "日期"))
d[, 日期 := as.Date(日期)]
d <- d[日期 >= as.Date("2024-06-01") & 日期 <= as.Date("2026-06-30")]
d[, 旗標 := trimws(旗標)]
# 排除 2026-05-24/25 的污染（與整併版清理一致），只看正常資料
d <- d[!(日期 %in% as.Date(c("2026-05-24", "2026-05-25")))]

d[, `:=`(
  站序有負99 = 上車站序 == -99 | 下車站序 == -99,
  站牌有負99 = grepl("-99", 上車站牌) | grepl("-99", 下車站牌),
  時間有1970 = grepl("^1970", 上車時間) | grepl("^1970", 下車時間)
)]

cat("=== 旗標 × 三種異常條件的交叉表（全期，已排除 5/24-25 污染）===\n")
print(d[, .(列數 = .N,
            `站序有-99` = sum(站序有負99, na.rm = TRUE),
            `站牌有-99` = sum(站牌有負99, na.rm = TRUE),
            時間有1970 = sum(時間有1970, na.rm = TRUE),
            `三者皆無` = sum(!站序有負99 & !站牌有負99 & !時間有1970, na.rm = TRUE)),
        by = 旗標][order(旗標)])

cat("\n=== 旗標為 1 者的組成拆解 ===\n")
f <- d[旗標 == "1"]
f[, 類型 := fcase(
  站序有負99 & 時間有1970, "站序 -99 且時間 1970",
  站序有負99, "僅站序 -99",
  時間有1970, "僅時間 1970",
  default = "皆非（旗標成因不明）")]
print(f[, .(列數 = .N, `占旗標1之%` = round(100 * .N / nrow(f), 1))][, 總計 := nrow(f)][])
print(f[, .(列數 = .N, `占比%` = round(100 * .N / nrow(f), 1)), by = 類型][order(-列數)])

cat("\n=== 旗標為 1 者：能否計算里程（站牌與站序是否可用）===\n")
print(f[, .(`站序任一為-99` = sum(站序有負99, na.rm = TRUE),
            `站序皆正常` = sum(!站序有負99, na.rm = TRUE))])

cat("\n=== 旗標為 0 者中，時間為 1970 的列數（旗標未涵蓋者）===\n")
print(d[旗標 == "0", .(列數 = .N, 時間有1970 = sum(時間有1970, na.rm = TRUE))])
