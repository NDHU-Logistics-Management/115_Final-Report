# 驗證：旗標為 1 的列，月份是怎麼歸的？
# 關鍵：「資料代表日期(yyyy-MM-dd)」是獨立欄位（第 30 欄），
#       與「刷卡上車時間」（16）、「刷卡下車時間」（20）不同欄。
# 本腳本證明：即使刷卡時間為 1970，資料代表日期仍是正常日期，月份由後者決定。
suppressPackageStartupMessages(library(data.table))
options(width = 210)
p <- "d:/Github/115_Final-Report/data/臺東縣公車.csv"
nm <- names(fread(p, nrows = 0))
cat("第 16 欄：", nm[16], "\n第 20 欄：", nm[20], "\n第 30 欄：", nm[30], "\n\n")

d <- fread(p, select = c(2, 14, 16, 18, 20, 26, 30),
           colClasses = list(character = c(1, 2, 4, 6)), showProgress = FALSE)
setnames(d, c("卡號", "上車站名", "刷卡上車時間", "下車站名", "刷卡下車時間", "旗標", "資料代表日期"))
d[, 旗標 := trimws(旗標)]
d[, 代表日 := as.Date(資料代表日期)]
d <- d[代表日 >= as.Date("2024-06-01") & 代表日 <= as.Date("2026-06-30")]
d <- d[!(代表日 %in% as.Date(c("2026-05-24", "2026-05-25")))]

cat("=== 旗標為 1 的列，隨機 8 筆原始內容（卡號遮蔽）===\n")
set.seed(1)
s <- d[旗標 == "1"][sample(.N, 8)]
s[, 卡號 := paste0(substr(卡號, 1, 6), "…")]
print(s[, .(卡號, 上車站名, 刷卡上車時間, 下車站名, 刷卡下車時間, 旗標, 資料代表日期)])

cat("\n=== 旗標為 1 的列：資料代表日期是否有效 ===\n")
f <- d[旗標 == "1"]
cat("總列數：", nrow(f),
    "  代表日為 1970 者：", sum(format(f$代表日, "%Y") == "1970"),
    "  代表日為 NA 者：", sum(is.na(f$代表日)), "\n")
cat("代表日範圍：", format(min(f$代表日)), "至", format(max(f$代表日)), "\n")

cat("\n=== 旗標為 1 的列：刷卡時間 1970 的組成 ===\n")
f[, `:=`(上1970 = grepl("^1970", 刷卡上車時間), 下1970 = grepl("^1970", 刷卡下車時間))]
print(f[, .(列數 = .N), by = .(上1970, 下1970)][order(-列數)])

cat("\n=== 114/09、114/10 兩個月：旗標為 1 的列數（依資料代表日期歸月）===\n")
f[, 月 := sprintf("%03d/%02d", as.integer(format(代表日, "%Y")) - 1911, as.integer(format(代表日, "%m")))]
print(f[月 %chin% c("114/08", "114/09", "114/10", "114/11"), .(旗標1列數 = .N), by = 月][order(月)])

cat("\n=== 114/09 旗標為 1 的列：代表日的逐日分布（前 12 日）===\n")
print(f[月 == "114/09", .(列數 = .N), by = 代表日][order(代表日)][1:12])
