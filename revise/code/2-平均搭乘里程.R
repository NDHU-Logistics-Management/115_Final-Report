# ============================================================
# 4. 建立「精確站序 fallback」表
# ============================================================

build_sequence_index = function(distance_index) {

  x = distance_index[
    !is.na(站序資料)
  ]


  # 同一路線 + 附屬路線 + 方向 + 站序
  # 只有累積里程唯一時才允許使用
  result = x[
    ,
    .(
      累積里程種類數 =
        uniqueN(
          累積里程
        ),

      站序補配里程 =
        if (
          uniqueN(累積里程) == 1
        ) {
          first(累積里程)
        } else {
          NA_real_
        }
    ),
    by = .(
      搭乘路線名稱,
      搭乘附屬路線名稱,
      搭乘公車路線方向,
      站序資料
    )
  ]


  return(result)
}


# ============================================================
# 5. 單一端點配對函數
#
# 例如：
# 上車站牌 / 上車站序
# 下車站牌 / 下車站序
# ============================================================

match_one_side = function(
  ticket,
  distance_index,
  stop_col,
  seq_col,
  side_name
) {

  # ----------------------------------------------------------
  # 建立票證配對資料
  # ----------------------------------------------------------

  t = ticket[
    ,
    .(
      ticket_id,
      搭乘路線名稱,
      搭乘附屬路線名稱,
      搭乘公車路線方向,

      配對站牌代碼 =
        normalize_stop_code(
          get(stop_col)
        ),

      票證站序 =
        as.numeric(
          get(seq_col)
        )
    )
  ]


  # ----------------------------------------------------------
  # 距離表
  # ----------------------------------------------------------

  d = copy(
    distance_index
  )

  setnames(
    d,
    old = c(
      "站牌代碼_標準",
      "站序資料",
      "累積里程"
    ),
    new = c(
      "配對站牌代碼",
      "距離表站序",
      "候選累積里程"
    )
  )


  # ==========================================================
  # A. 第一層：站牌代碼配對
  # ==========================================================

  stop_candidates = merge(
    t[
      !is.na(配對站牌代碼)
    ],
    d[
      !is.na(配對站牌代碼)
    ],
    by = c(
      "搭乘路線名稱",
      "搭乘附屬路線名稱",
      "搭乘公車路線方向",
      "配對站牌代碼"
    ),
    allow.cartesian = TRUE,
    sort = FALSE
  )


  # ----------------------------------------------------------
  # 計算站序差
  # ----------------------------------------------------------

  stop_candidates[
    ,
    站序差 :=
      fifelse(
        !is.na(票證站序) &
        票證站序 != -99 &
        !is.na(距離表站序),

        abs(
          票證站序 -
          距離表站序
        ),

        NA_real_
      )
  ]


  # ==========================================================
  # 每張票選最合理站點
  # ==========================================================

  if (nrow(stop_candidates) > 0) {

    stop_match = stop_candidates[
      ,
      {

        # --------------------------------------------
        # 情況 1：
        # 有有效票證站序
        # --------------------------------------------

        if (
          !is.na(票證站序[1]) &&
          票證站序[1] != -99
        ) {

          min_diff = min(
            站序差,
            na.rm = TRUE
          )

          z = .SD[
            站序差 == min_diff
          ]


          # 最小站序差候選最後仍只有一種累積里程
          if (
            uniqueN(
              z$候選累積里程
            ) == 1
          ) {

            list(
              配對里程 =
                z$候選累積里程[1],

              配對方法 =
                if (min_diff == 0) {
                  "站牌代碼+站序精確"
                } else {
                  "站牌代碼+站序輔助"
                },

              配對站序差 =
                min_diff
            )

          } else {

            # 同樣最近但有多種里程
            # 不猜
            list(
              配對里程 =
                NA_real_,

              配對方法 =
                "站牌代碼候選歧義",

              配對站序差 =
                min_diff
            )
          }


        # --------------------------------------------
        # 情況 2：
        # 站序 = -99 或 NA
        # --------------------------------------------

        } else {

          # 只有一種累積里程時
          # 站牌本身就足以定位
          if (
            uniqueN(
              候選累積里程
            ) == 1
          ) {

            list(
              配對里程 =
                first(
                  候選累積里程
                ),

              配對方法 =
                "唯一站牌代碼",

              配對站序差 =
                NA_real_
            )

          } else {

            # 同一站牌出現多個不同位置
            # 又沒有有效站序可判斷
            list(
              配對里程 =
                NA_real_,

              配對方法 =
                "站牌代碼候選歧義",

              配對站序差 =
                NA_real_
            )
          }
        }
      },
      by = ticket_id
    ]

  } else {

    stop_match = data.table(
      ticket_id = integer(),
      配對里程 = numeric(),
      配對方法 = character(),
      配對站序差 = numeric()
    )
  }


  # ==========================================================
  # B. 第二層：
  # 站牌代碼仍配不到時，才用精確站序 fallback
  # ==========================================================

  result = merge(
    t,
    stop_match,
    by = "ticket_id",
    all.x = TRUE,
    sort = FALSE
  )


  sequence_index =
    build_sequence_index(
      distance_index
    )


  seq_temp = result[
    is.na(配對里程) &
    !is.na(票證站序) &
    票證站序 != -99,
    .(
      ticket_id,
      搭乘路線名稱,
      搭乘附屬路線名稱,
      搭乘公車路線方向,
      站序資料 =
        票證站序
    )
  ]


  if (nrow(seq_temp) > 0) {

    seq_match = merge(
      seq_temp,
      sequence_index,
      by = c(
        "搭乘路線名稱",
        "搭乘附屬路線名稱",
        "搭乘公車路線方向",
        "站序資料"
      ),
      all.x = TRUE,
      sort = FALSE
    )


    seq_match = seq_match[
      ,
      .(
        ticket_id,
        站序補配里程
      )
    ]


    result = merge(
      result,
      seq_match,
      by = "ticket_id",
      all.x = TRUE,
      sort = FALSE
    )


    # 只有尚未配到，且站序 fallback 有唯一答案時才補
    result[
      is.na(配對里程) &
      !is.na(站序補配里程),
      `:=`(
        配對里程 =
          站序補配里程,

        配對方法 =
          "站序精確補配",

        配對站序差 =
          0
      )
    ]

  } else {

    result[
      ,
      站序補配里程 :=
        NA_real_
    ]
  }


  # ==========================================================
  # C. 最後仍失敗
  # ==========================================================

  result[
    is.na(配對里程) &
    is.na(配對方法),
    配對方法 :=
      "未配對"
  ]


  # 原本有站牌候選歧義但 fallback 也失敗
  # 保留「候選歧義」資訊，不改成未配對


  # ==========================================================
  # D. 整理欄位名稱
  # ==========================================================

  output = result[
    ,
    .(
      ticket_id,
      配對里程,
      配對方法,
      配對站序差
    )
  ]


  setnames(
    output,
    old = c(
      "配對里程",
      "配對方法",
      "配對站序差"
    ),
    new = c(
      paste0(
        side_name,
        "里程"
      ),

      paste0(
        side_name,
        "配對方法"
      ),

      paste0(
        side_name,
        "站序差"
      )
    )
  )


  return(output)
}


# ============================================================
# 6. 月平均搭乘里程主函數
# ============================================================

calculate_monthly_mileage = function(
  ticket_data,
  distance_index
) {

  ticket = copy(
    as.data.table(
      ticket_data
    )
  )


  # ==========================================================
  # 基本格式
  # ==========================================================

  ticket[
    ,
    搭乘路線名稱 :=
      trimws(
        as.character(
          搭乘路線名稱
        )
      )
  ]

  ticket[
    ,
    搭乘附屬路線名稱 :=
      trimws(
        as.character(
          搭乘附屬路線名稱
        )
      )
  ]

  ticket[
    ,
    搭乘公車路線方向 :=
      as.character(
        搭乘公車路線方向
      )
  ]

  ticket[
    ,
    上車站牌代碼 :=
      as.character(
        上車站牌代碼
      )
  ]

  ticket[
    ,
    下車站牌代碼 :=
      as.character(
        下車站牌代碼
      )
  ]

  ticket[
    ,
    上車計費站序資料 :=
      as.numeric(
        上車計費站序資料
      )
  ]

  ticket[
    ,
    下車站牌站序 :=
      as.numeric(
        下車站牌站序
      )
  ]

  ticket[
    ,
    原始票證筆數 :=
      as.numeric(
        原始票證筆數
      )
  ]

  ticket[
    ,
    `資料代表日期(yyyy-MM-dd)` :=
      as.Date(
        `資料代表日期(yyyy-MM-dd)`
      )
  ]


  # ==========================================================
  # 分析期間
  # 113/06 ～ 115/06
  # ==========================================================

  ticket = ticket[
    `資料代表日期(yyyy-MM-dd)` >=
      as.Date("2024-06-01") &
    `資料代表日期(yyyy-MM-dd)` <=
      as.Date("2026-06-30")
  ]


  # ==========================================================
  # 原始票證筆數
  # ==========================================================

  ticket = ticket[
    !is.na(原始票證筆數) &
    原始票證筆數 > 0
  ]


  # 唯一 ID
  ticket[
    ,
    ticket_id :=
      .I
  ]


  # ==========================================================
  # 上車站配對
  # ==========================================================

  on_match = match_one_side(
    ticket = ticket,
    distance_index = distance_index,
    stop_col = "上車站牌代碼",
    seq_col = "上車計費站序資料",
    side_name = "上車"
  )


  # ==========================================================
  # 下車站配對
  # ==========================================================

  off_match = match_one_side(
    ticket = ticket,
    distance_index = distance_index,
    stop_col = "下車站牌代碼",
    seq_col = "下車站牌站序",
    side_name = "下車"
  )


  # ==========================================================
  # 合併
  # ==========================================================

  ticket = merge(
    ticket,
    on_match,
    by = "ticket_id",
    all.x = TRUE,
    sort = FALSE
  )

  ticket = merge(
    ticket,
    off_match,
    by = "ticket_id",
    all.x = TRUE,
    sort = FALSE
  )


  setorder(
    ticket,
    ticket_id
  )


  # ==========================================================
  # 計算每筆搭乘里程
  #
  # 確認上下車都是同一路線資料後，
  # 只計 下車里程 - 上車里程 > 0 者；差 < 0（閉合表反向）與
  # 差 = 0（上下車同站）設為 NA，不計入延人公里與人次 [修訂 C5，採獨立腳本規則]
  # ==========================================================

  ticket[
    ,
    里程_公尺 :=
      fifelse(
        !is.na(上車里程) &
        !is.na(下車里程) &
        下車里程 - 上車里程 > 0,

        下車里程 -
          上車里程,

        NA_real_
      )
  ]


  # ==========================================================
  # 建立月份
  # ==========================================================

  ticket[
    ,
    月份 :=
      sprintf(
        "%03d/%02d",

        as.integer(
          format(
            `資料代表日期(yyyy-MM-dd)`,
            "%Y"
          )
        ) - 1911,

        as.integer(
          format(
            `資料代表日期(yyyy-MM-dd)`,
            "%m"
          )
        )
      )
  ]


  # ==========================================================
  # 月平均搭乘里程
  #
  # 總延人公里 =
  # sum(里程 × 原始票證筆數)
  #
  # 平均 =
  # 總延人公里 / 成功配對載客人次
  # ==========================================================

  result = ticket[
    !is.na(里程_公尺),
    .(

      搭乘人次 = .N,

      總延人公里 = sum(里程_公尺, na.rm = TRUE) / 1000

    ),
    by = 月份
  ]


  result[
    ,
    平均搭乘里程_公里 :=
      總延人公里 /
      搭乘人次
  ]


  result[
    ,
    `:=`(

      總延人公里 =
        round(
          總延人公里,
          2
        ),

      平均搭乘里程_公里 =
        round(
          平均搭乘里程_公里,
          2
        )
    )
  ]


  setorder(
    result,
    月份
  )


  # ==========================================================
  # 配對成功率檢查
  # ==========================================================

  check = ticket[
    ,
    .(

      總筆數 =
        .N,

      成功筆數 =
        sum(
          !is.na(
            里程_公尺
          )
        ),

      失敗筆數 =
        sum(
          is.na(
            里程_公尺
          )
        ),

      成功率 =
        round(
          mean(
            !is.na(
              里程_公尺
            )
          ) * 100,
          2
        ),

      原始載客人次 = .N,

      成功配對載客人次 = sum(!is.na(里程_公尺))
    )
  ]


  # 載客人次配對率
  check[
    ,
    載客人次成功率 :=
      round(
        成功配對載客人次 /
        原始載客人次 *
        100,
        2
      )
  ]


  # ==========================================================
  # 上車配對方法統計
  # ==========================================================

  on_method = ticket[
    ,
    .(
      筆數 = .N,
      載客人次 = .N
    ),
    by = 上車配對方法
  ][
    order(-筆數)
  ]


  # ==========================================================
  # 下車配對方法統計
  # ==========================================================

  off_method = ticket[
    ,
    .(
      筆數 = .N,
      載客人次 = .N
    ),
    by = 下車配對方法
  ][
    order(-筆數)
  ]


  # ==========================================================
  # 失敗資料
  # ==========================================================

  unmatched = ticket[
    is.na(
      里程_公尺
    )
  ]


  return(
    list(
      monthly = result,
      detail = ticket,
      check = check,
      on_method = on_method,
      off_method = off_method,
      unmatched = unmatched
    )
  )
}


