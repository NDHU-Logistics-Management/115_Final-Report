# 11. 畫圖函數
#
# 格式沿用原本 115 期末平均搭乘里程圖
# ============================================================

plot_monthly_average_mileage = function(
  data,
  title_main,
  filename,
  flag = NULL,
  vline = NULL
) {

  color = gray.colors(2)


  # ----------------------------------------------------------
  # Y 軸上下限
  # ----------------------------------------------------------

  ymin = min(
    data$平均搭乘里程_公里,
    na.rm = TRUE
  )

  ymax = max(
    data$平均搭乘里程_公里,
    na.rm = TRUE
  )


  if (ymin == ymax) {

    y_lower =
      ymin * 0.9

    y_upper =
      ymax * 1.1

  } else {

    y_lower =
      ymin * 0.9

    y_upper =
      ymax * 1.2
  }


  # 若全部非常接近 0
  if (
    !is.finite(y_lower) ||
    !is.finite(y_upper) ||
    y_lower == y_upper
  ) {

    y_lower = 0

    y_upper =
      max(
        1,
        ymax + 1
      )
  }


  # ==========================================================
  # 開圖
  # ==========================================================

  png(
    filename = file.path(FIG_DIR, filename),
    width = 15,
    height = 5,
    units = "in",
    res = 300
  )


  par(
    family = "msjh",
    mar = c(5, 6, 4, 8),
    mgp = c(3.5, 0.8, 0),
    bty = "l",
    cex.lab = 1.5
  )


  # ==========================================================
  # 主圖
  # ==========================================================

  plot(
    x = 1:nrow(data),
    y = data$平均搭乘里程_公里,

    type = "o",

    lwd = 2,
    pch = 16,

    col = color[1],

    xlab = "月份",
    ylab = "",

    ylim = c(
      y_lower,
      y_upper
    ),

    cex.main = 2,
    cex.lab = 2,
    cex.axis = 1.5,
    cex = 1.5,

    xaxt = "n",
    yaxt = "n",

    bty = "n"
  )


  # ==========================================================
  # 標題
  # ==========================================================

  title(
    main = title_main,
    cex.main = 2,
    adj = 0
  )


  # ==========================================================
  # X 軸
  # ==========================================================

  axis(
    side = 1,
    at = 1:nrow(data),
    labels = data$月份,
    cex.axis = 1.25
  )


  # ==========================================================
  # Y 軸
  # ==========================================================

  y_ticks = pretty(
    c(
      y_lower,
      y_upper
    ),
    n = 5
  )


  axis(
    side = 2,
    at = y_ticks,
    labels = round(
      y_ticks,
      1
    ),
    las = 1,
    cex.axis = 1.5
  )


  # ==========================================================
  # 網格
  # ==========================================================

  abline(
    h = y_ticks,
    col = "grey80",
    lty = 1,
    lwd = 0.8
  )


  abline(
    v = 1:nrow(data),
    col = "grey90",
    lty = 1,
    lwd = 0.6
  )


  # ==========================================================
  # 折線重畫
  # 避免被網格蓋住
  # ==========================================================

  # [修訂 A6] 路線改號時點
  flag_vline(data$月份, vline)

  lines(
    x = 1:nrow(data),
    y = data$平均搭乘里程_公里,
    type = "o",
    lwd = 2,
    pch = 16,
    col = color[1]
  )

  # [修訂 A1/A2] 業者資料不完整月份
  flag_points(1:nrow(data), data$平均搭乘里程_公里, data$月份, flag, cex = 1.9)


  # ==========================================================
  # 點上數值
  # ==========================================================

  text(
    x = 1:nrow(data),

    y =
      data$平均搭乘里程_公里 +
      diff(
        range(
          c(
            y_lower,
            y_upper
          )
        )
      ) * 0.025,

    labels =
      sprintf(
        "%.1f",
        data$平均搭乘里程_公里
      ),

    pos = 3,

    cex = 1.1,

    col = "black"
  )


  # ==========================================================
  # 圖例
  # ==========================================================

  legend(
    "topright",

    legend =
      "公里",

    col =
      color[1],

    lwd =
      2,

    pch =
      16,

    bty =
      "n",

    inset =
      c(
        -0.1,
        0
      ),

    xpd =
      TRUE,

    cex =
      1.5
  )


  dev.off()
}




