# ============================================================
# 月平均搭乘里程
#
# 配對原則：
# 1. 站牌代碼優先
# 2. 同一站牌有多筆候選時，以站序差最小者選擇
# 3. 站序為 -99 時，只要站牌代碼能唯一決定累積里程即可使用
# 4. 站牌代碼無法配對時，才使用「站序完全相同」補配
# 5. 不使用無限制最近站序硬配
# 6. 最後仍配不到者保留 NA
# 7. 上下車都成功配對後，只計 下車里程 - 上車里程 > 0 者；差 <= 0（反向、同站）不計入 [修訂 C5]
# 8. 一列計為一人次（原始票證筆數為平臺重複計數，非搭乘次數，不加權）[修訂 C4]
#
# 平均搭乘里程 =
# 總延人公里 / 載客人數
#
# 總延人公里 =
# sum(每筆搭乘里程)
#
# 載客人數 =
# 紀錄筆數 .N
# ============================================================


# ============================================================
# 1. 站牌代碼標準化
# ============================================================

normalize_stop_code = function(x) {

  x = trimws(
    toupper(
      as.character(x)
    )
  )

  # 花蓮資料曾出現 HUA 前綴
  # 與期中程式處理方式一致
  x = sub(
    "^HUA",
    "",
    x
  )

  # 空值轉 NA
  x[
    x %in% c(
      "",
      "NA",
      "N/A",
      "NULL"
    )
  ] = NA_character_

  return(x)
}


# ============================================================
# 2. 建立站距累積里程索引
# ============================================================

build_distance_index = function(distance_data) {

  x = copy(
    as.data.table(distance_data)
  )


  # ----------------------------------------------------------
  # 格式統一
  # ----------------------------------------------------------

  x[
    ,
    搭乘路線名稱 :=
      trimws(
        as.character(
          搭乘路線名稱
        )
      )
  ]

  x[
    ,
    搭乘附屬路線名稱 :=
      trimws(
        as.character(
          搭乘附屬路線名稱
        )
      )
  ]

  x[
    ,
    搭乘公車路線方向 :=
      as.character(
        搭乘公車路線方向
      )
  ]

  x[
    ,
    站牌代碼_標準 :=
      normalize_stop_code(
        站牌代碼
      )
  ]

  x[
    ,
    站序資料 :=
      as.numeric(
        站序資料
      )
  ]

  x[
    ,
    站間距離 :=
      as.numeric(
        站間距離
      )
  ]


  # ----------------------------------------------------------
  # NA 站間距離視為 0
  # ----------------------------------------------------------

  x[
    is.na(站間距離),
    站間距離 := 0
  ]


  # ----------------------------------------------------------
  # 排序
  # ----------------------------------------------------------

  setorder(
    x,
    搭乘路線名稱,
    搭乘附屬路線名稱,
    搭乘公車路線方向,
    站序資料
  )


  # ----------------------------------------------------------
  # 建立累積里程
  # ----------------------------------------------------------

  x[
    ,
    累積里程 :=
      cumsum(
        站間距離
      ),
    by = .(
      搭乘路線名稱,
      搭乘附屬路線名稱,
      搭乘公車路線方向
    )
  ]


  # ----------------------------------------------------------
  # 保留需要欄位
  # ----------------------------------------------------------

  x = x[
    ,
    .(
      搭乘路線名稱,
      搭乘附屬路線名稱,
      搭乘公車路線方向,
      站牌代碼_標準,
      站序資料,
      累積里程
    )
  ]


  # 完全相同資料去重
  x = unique(
    x
  )


  return(x)
}


