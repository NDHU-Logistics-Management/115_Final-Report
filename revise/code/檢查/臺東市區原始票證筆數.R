# 第 3 章檢查：臺東市區特殊月份的原始票證筆數分布
# 不影響輸出。
# ============================================================

source(file.path(if (exists("CODE_DIR")) CODE_DIR else ".", "00_設定.R"), encoding = "UTF-8")
ensure_clean_data()

# ============================================================
# 檢查臺東市區特殊月份的原始票證筆數
# ============================================================

臺東市區_check = copy(臺東市區_clean)

臺東市區_check[
  ,
  `資料代表日期(yyyy-MM-dd)` :=
    as.Date(
      `資料代表日期(yyyy-MM-dd)`
    )
]

臺東市區_check[
  ,
  西元年月 :=
    format(
      `資料代表日期(yyyy-MM-dd)`,
      "%Y-%m"
    )
]


# 各月份原始票證筆數分布
臺東市區_check[
  西元年月 %in% c(
    "2024-06",
    "2024-07",
    "2024-08",
    "2025-01",
    "2025-02",
    "2025-03"
  ),
  .N,
  by = .(
    西元年月,
    原始票證筆數
  )
][
  order(
    西元年月,
    原始票證筆數
  )
]

# 各月份原始票證筆數最小值、平均值、最大值

臺東市區_check[
  ,
  .(
    最小值 =
      min(
        原始票證筆數,
        na.rm = TRUE
      ),

    中位數 =
      median(
        原始票證筆數,
        na.rm = TRUE
      ),

    平均值 =
      mean(
        原始票證筆數,
        na.rm = TRUE
      ),

    最大值 =
      max(
        原始票證筆數,
        na.rm = TRUE
      )
  ),
  by = 西元年月
][
  order(
    西元年月
  )
]
