if (!exists("花蓮市區")) source(file.path(CODE_DIR, "01_load_data.R"), encoding = "UTF-8")

# 1. 看目前花蓮市區的筆數
nrow(
  花蓮市區
)


# ============================================================
# 2. 直接重新確認所有搭乘附屬路線代碼
# ============================================================

table(
  花蓮市區$搭乘附屬路線代碼,
  useNA = "ifany"
)


# ============================================================
# 3. 看所有以 HSZ 開頭的搭乘附屬路線代碼
# ============================================================

花蓮市區[
  grepl(
    "^HSZ",
    trimws(
      as.character(
        搭乘附屬路線代碼
      )
    )
  ),
  .N,
  by = .(
    搭乘附屬路線代碼
  )
][
  order(
    搭乘附屬路線代碼
  )
]


# ============================================================
# 4. 同時看「搭乘附屬路線代碼」與「搭乘路線名稱」
# ============================================================

花蓮市區[
  grepl(
    "^HSZ",
    trimws(
      as.character(
        搭乘附屬路線代碼
      )
    )
  ),
  .N,
  by = .(
    搭乘附屬路線代碼,
    搭乘路線名稱
  )
][
  order(
    搭乘附屬路線代碼,
    搭乘路線名稱
  )
]


# ============================================================
# 5. HSZ 開頭的搭乘附屬路線代碼總筆數
# ============================================================

