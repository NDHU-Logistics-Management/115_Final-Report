# ============================================================
# 畫圖函數
# ============================================================

plot_average_transfer = function(
  data,
  title,
  filename,
  flag = NULL
) {

  # ==========================================================
  # 顏色設定
  # ==========================================================

  color =
    gray.colors(
      3,
      start = 0.3,
      end = 0.75
    )


  # ==========================================================
  # X 軸
  # ==========================================================

  x =
    1:nrow(data)


  # ==========================================================
  # 三組數值
  # ==========================================================

  y1 =
    data$平均轉乘次數

  y2 =
    data$TPASS平均轉乘次數

  y3 =
    data$其他票種平均轉乘次數


  # ==========================================================
  # Y 軸範圍
  # ==========================================================

  y_all =
    c(
      y1,
      y2,
      y3
    )


  ymin =
    min(
      y_all,
      na.rm = TRUE
    )


  ymax =
    max(
      y_all,
      na.rm = TRUE
    )


  y_range =
    ymax - ymin


  if (
    !is.finite(y_range) ||
    y_range == 0
  ) {

    y_range =
      0.01
  }


  y_lower =
    max(
      0,
      ymin -
        y_range * 0.15
    )


  y_upper =
    ymax +
      y_range * 0.20


  # ==========================================================
  # Y 軸刻度
  # ==========================================================

  y_ticks =
    pretty(
      c(
        y_lower,
        y_upper
      ),
      n = 5
    )


  # ==========================================================
  # 輸出 PNG
  # ==========================================================

  png(
    filename = file.path(FIG_DIR, filename),
    width = 15,
    height = 5,
    units = "in",
    res = 300
  )


  # ==========================================================
  # 圖形格式
  # ==========================================================

  par(
    family = "msjh",
    mar = c(5, 6, 4, 8),
    mgp = c(3.5, 0.8, 0),
    bty = "l",
    cex.lab = 1.5
  )


  # ==========================================================
  # 建立主圖
  # ==========================================================

  plot(
    x,
    y1,

    type = "n",

    xlim = c(
      1,
      nrow(data)
    ),

    ylim = c(
      y_lower,
      y_upper
    ),

    xaxt = "n",
    yaxt = "n",

    xlab = "月份",
    ylab = "平均轉乘次數",

    main = "",
    cex.main = 1.7,
    cex.lab = 1.5
  )


  # ==========================================================
  # 水平網格
  # ==========================================================

  abline(
    h = y_ticks,
    col = "grey80",
    lty = 1,
    lwd = 0.8
  )


  # ==========================================================
  # 垂直網格
  # 每個月
  # ==========================================================

  abline(
    v = x,
    col = "grey90",
    lty = 1,
    lwd = 0.6
  )


  # ==========================================================
  # 全部乘客
  # ==========================================================

  lines(
    x,
    y1,
    type = "o",
    pch = 16,
    lty = 1,
    lwd = 1.7,
    cex = 1,
    col = color[1]
  )


  # ==========================================================
  # TPASS
  # ==========================================================

  lines(
    x,
    y2,
    type = "o",
    pch = 16,
    lty = 1,
    lwd = 1.7,
    cex = 1,
    col = color[2]
  )


  # ==========================================================
  # 其他票種
  # ==========================================================

  lines(
    x,
    y3,
    type = "o",
    pch = 16,
    lty = 1,
    lwd = 1.7,
    cex = 1,
    col = color[3]
  )

  # [修訂 A1/A2] 業者資料不完整月份（三條線都標）
  flag_points(x, y1, data$月份, flag, cex = 1.3)
  flag_points(x, y2, data$月份, flag, cex = 1.3)
  flag_points(x, y3, data$月份, flag, cex = 1.3)

  # [修訂] 主標題置左
  title(main = title, adj = 0, cex.main = 1.7)


  # ==========================================================
  # X 軸
  # 每 2 個月顯示一次
  # ==========================================================

  x_pos =
    seq(
      1,
      nrow(data),
      by = 2
    )


  axis(
    side = 1,
    at = x_pos,
    labels =
      data$月份[x_pos],
    las = 1,
    cex.axis = 1.2
  )


  # ==========================================================
  # Y 軸
  # 小數點後 3 位
  # ==========================================================

  axis(
    side = 2,
    at = y_ticks,
    labels =
      sprintf(
        "%.3f",
        y_ticks
      ),
    las = 1,
    cex.axis = 1.2
  )


  # ==========================================================
  # 圖例
  # ==========================================================

  legend(
    "topright",

    inset = c(
      -0.1,
      0
    ),

    legend = c(
      "平均轉乘次數",
      "TPASS",
      "其他票種"
    ),

    col = color,

    pch = c(
      16,
      16,
      16
    ),

    lty = c(
      1,
      1,
      1
    ),

    lwd = 1.7,

    bty = "n",

    xpd = TRUE,

    cex = 1.2
  )


  dev.off()
}


