# ============================================================
# 1. 日期時間轉換函數
# ============================================================

parse_datetime = function(x) {

  x =
    trimws(
      as.character(x)
    )


  # ----------------------------------------------------------
  # YYYY-MM-DD HH:MM:SS
  # ----------------------------------------------------------

  result =
    as.POSIXct(
      x,
      format = "%Y-%m-%d %H:%M:%S",
      tz = "Asia/Taipei"
    )


  # ----------------------------------------------------------
  # YYYY/MM/DD HH:MM:SS
  # ----------------------------------------------------------

  idx =
    is.na(result) &
    !is.na(x) &
    x != ""


  result[idx] =
    as.POSIXct(
      x[idx],
      format = "%Y/%m/%d %H:%M:%S",
      tz = "Asia/Taipei"
    )


  # ----------------------------------------------------------
  # YYYY/MM/DD HH:MM
  # ----------------------------------------------------------

  idx =
    is.na(result) &
    !is.na(x) &
    x != ""


  result[idx] =
    as.POSIXct(
      x[idx],
      format = "%Y/%m/%d %H:%M",
      tz = "Asia/Taipei"
    )


  return(result)
}


# ============================================================
# 2. 平均轉乘次數函數
# ============================================================

calculate_average_transfer = function(
  data,
  transfer_limit = 120
) {

  x =
    copy(
      as.data.table(data)
    )


  # ==========================================================
  # A. 基本格式
  # ==========================================================

  x[
    ,
    `資料代表日期(yyyy-MM-dd)` :=
      as.Date(
        `資料代表日期(yyyy-MM-dd)`
      )
  ]


  x[
    ,
    卡號 :=
      trimws(
        as.character(
          卡號
        )
      )
  ]


  x[
    ,
    搭乘路線名稱 :=
      trimws(
        as.character(
          搭乘路線名稱
        )
      )
  ]


  x[
    ,
    票種次類型 :=
      trimws(
        as.character(
          票種次類型
        )
      )
  ]


  # ==========================================================
  # B. 上下車時間
  # ==========================================================

  x[
    ,
    上車時間 :=
      parse_datetime(
        刷卡上車時間
      )
  ]


  x[
    ,
    下車時間 :=
      parse_datetime(
        刷卡下車時間
      )
  ]


  # ==========================================================
  # C. 分析期間
  # ==========================================================

  x =
    x[
      `資料代表日期(yyyy-MM-dd)` >=
        start_date &
      `資料代表日期(yyyy-MM-dd)` <=
        end_date
    ]


  # ==========================================================
  # D. 排除無法進行轉乘追蹤的紀錄
  #
  # 注意：
  # 不需要依原始票證筆數篩選
  # 因為本分析使用的是「可追蹤搭乘紀錄」
  # ==========================================================

  x =
    x[
      !is.na(
        `資料代表日期(yyyy-MM-dd)`
      ) &
      !is.na(卡號) &
      卡號 != "" &
      !is.na(搭乘路線名稱) &
      搭乘路線名稱 != "" &
      !is.na(上車時間) &
      !is.na(下車時間)
    ]


  # ==========================================================
  # E. 建立月份
  # ==========================================================

  x[
    ,
    月份 :=
      sprintf(
        "%03d/%02d",

        as.integer(
          format(
            `資料代表日期(yyyy-MM-dd)`,
            "%Y"
          )
        ) - 1911,

        as.integer(
          format(
            `資料代表日期(yyyy-MM-dd)`,
            "%m"
          )
        )
      )
  ]


  # ==========================================================
  # F. TPASS / 其他票種
  # ==========================================================

  x[
    ,
    票種分類 :=
      fifelse(
        票種次類型 %in%
          tpass_types,
        "TPASS",
        "其他票種"
      )
  ]


  # ==========================================================
  # G. 排序
  #
  # 只依：
  # 日期 + 卡號 + 上車時間
  #
  # 不依業者分組
  # ==========================================================

  setorder(
    x,
    `資料代表日期(yyyy-MM-dd)`,
    卡號,
    上車時間,
    下車時間
  )


  # ==========================================================
  # H. 取得前一趟資訊
  #
  # 同一卡號 + 同一天
  # ==========================================================

  x[
    ,
    `:=`(

      前一趟下車時間 =
        shift(
          下車時間,
          type = "lag"
        ),

      前一趟路線 =
        shift(
          搭乘路線名稱,
          type = "lag"
        )

    ),
    by = .(
      `資料代表日期(yyyy-MM-dd)`,
      卡號
    )
  ]


  # ==========================================================
  # I. 前後搭乘時間間隔
  # ==========================================================

  x[
    ,
    轉乘間隔分鐘 :=
      as.numeric(
        difftime(
          上車時間,
          前一趟下車時間,
          units = "mins"
        )
      )
  ]


  # ==========================================================
  # J. 是否不同路線
  # ==========================================================

  x[
    ,
    是否不同路線 :=
      !is.na(
        前一趟路線
      ) &
      搭乘路線名稱 !=
        前一趟路線
  ]


  # ==========================================================
  # K. 是否轉乘
  #
  # 條件：
  #
  # 1. 同一卡號
  # 2. 同一天
  # 3. 相鄰紀錄
  # 4. 前次下車 -> 本次上車
  #    0 ～ transfer_limit 分鐘
  # 5. 前後路線不同
  # ==========================================================

  x[
    ,
    是否轉乘 :=
      fifelse(

        !is.na(
          轉乘間隔分鐘
        ) &

        轉乘間隔分鐘 >=
          0 &

        轉乘間隔分鐘 <=
          transfer_limit &

        是否不同路線,

        1L,
        0L
      )
  ]


  # ==========================================================
  # L. 每月統計
  #
  # 重要：
  #
  # 此處不能使用：
  #
  # sum(原始票證筆數)
  #
  # 因為轉乘事件本身只能在
  # 可追蹤的相鄰紀錄間判斷。
  #
  # 因此分子與分母都使用
  # 「可追蹤搭乘紀錄」為單位。
  # ==========================================================

  monthly =
    x[
      ,
      .(

        # ======================================================
        # 全部
        # ======================================================

        總搭乘紀錄數 =
          .N,

        總轉乘次數 =
          sum(
            是否轉乘,
            na.rm = TRUE
          ),


        # ======================================================
        # TPASS
        # ======================================================

        TPASS搭乘紀錄數 =
          sum(
            票種分類 ==
              "TPASS",
            na.rm = TRUE
          ),

        TPASS轉乘次數 =
          sum(
            是否轉乘 == 1 &
            票種分類 == "TPASS",
            na.rm = TRUE
          ),


        # ======================================================
        # 其他票種
        # ======================================================

        其他票種搭乘紀錄數 =
          sum(
            票種分類 ==
              "其他票種",
            na.rm = TRUE
          ),

        其他票種轉乘次數 =
          sum(
            是否轉乘 == 1 &
            票種分類 == "其他票種",
            na.rm = TRUE
          )

      ),
      by = 月份
    ]


  # ==========================================================
  # M. 平均轉乘次數
  # ==========================================================

  monthly[
    ,
    平均轉乘次數 :=
      fifelse(

        總搭乘紀錄數 >
          0,

        總轉乘次數 /
          總搭乘紀錄數,

        NA_real_
      )
  ]


  monthly[
    ,
    TPASS平均轉乘次數 :=
      fifelse(

        TPASS搭乘紀錄數 >
          0,

        TPASS轉乘次數 /
          TPASS搭乘紀錄數,

        NA_real_
      )
  ]


  monthly[
    ,
    其他票種平均轉乘次數 :=
      fifelse(

        其他票種搭乘紀錄數 >
          0,

        其他票種轉乘次數 /
          其他票種搭乘紀錄數,

        NA_real_
      )
  ]


  # ==========================================================
  # N. 四捨五入
  # ==========================================================

  monthly[
    ,
    `:=`(

      平均轉乘次數 =
        round(
          平均轉乘次數,
          4
        ),

      TPASS平均轉乘次數 =
        round(
          TPASS平均轉乘次數,
          4
        ),

      其他票種平均轉乘次數 =
        round(
          其他票種平均轉乘次數,
          4
        )
    )
  ]


  # ==========================================================
  # O. 月份排序
  # ==========================================================

  monthly[
    ,
    月份排序 :=
      as.integer(
        substr(
          月份,
          1,
          3
        )
      ) * 12 +
      as.integer(
        substr(
          月份,
          5,
          6
        )
      )
  ]


  setorder(
    monthly,
    月份排序
  )


  monthly[
    ,
    月份排序 := NULL
  ]


  # ==========================================================
  # P. 檢查表
  # ==========================================================

  check =
    x[
      ,
      .(

        可追蹤搭乘紀錄數 =
          .N,

        可辨識轉乘事件數 =
          sum(
            是否轉乘,
            na.rm = TRUE
          ),

        轉乘比例 =
          round(
            mean(
              是否轉乘,
              na.rm = TRUE
            ) * 100,
            2
          ),

        最小轉乘間隔 =
          min(
            轉乘間隔分鐘[
              是否轉乘 == 1
            ],
            na.rm = TRUE
          ),

        最大轉乘間隔 =
          max(
            轉乘間隔分鐘[
              是否轉乘 == 1
            ],
            na.rm = TRUE
          )

      )
    ]


  # ==========================================================
  # Q. 回傳
  # ==========================================================

  return(
    list(

      monthly =
        monthly,

      detail =
        x,

      check =
        check
    )
  )
}


