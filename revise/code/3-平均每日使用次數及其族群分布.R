# ============================================================
# Part B
# 2. 全部乘客各搭乘次數區間月人數變化表
#
# 每位乘客每月使用次數 =
# 該卡該月紀錄筆數 .N
#
# 分類：
#
# 僅一次   = 1
# 二至四次 = 2～4
# 五次以上 = >= 5
#
# 注意：
# 這裡是「全部乘客」
# 不篩 TPASS
# ============================================================

calculate_frequency_table = function(
  data,
  tpass_only = FALSE
) {

  x = prepare_usage_data(
    data
  )


  # ==========================================================
  # 如果指定 TPASS only
  # ==========================================================

  if (tpass_only) {

    x = x[
      票種次類型 %in%
        tpass_types
    ]
  }


  # ==========================================================
  # 每位乘客每月總使用次數
  #
  # 一列 =
  # 一個月份 + 一張卡號
  # ==========================================================

  person_month = x[
    ,
    .(
      每人每月使用次數 = .N
    ),
    by = .(
      西元年月,
      卡號
    )
  ]


  # ==========================================================
  # 分類
  # ==========================================================

  person_month[
    ,
    搭乘次數區間 :=
      fcase(

        每人每月使用次數 == 1,
        "僅一次",

        每人每月使用次數 >= 2 &
        每人每月使用次數 <= 4,
        "二至四次",

        每人每月使用次數 >= 5,
        "五次以上",

        default =
          NA_character_
      )
  ]


  # ==========================================================
  # 每月總使用人數
  # ==========================================================

  monthly_total = person_month[
    ,
    .(
      使用人數 =
        .N
    ),
    by = 西元年月
  ]


  # ==========================================================
  # 每月各區間人數
  # ==========================================================

  monthly_group = person_month[
    !is.na(搭乘次數區間),
    .(
      人數 =
        .N
    ),
    by = .(
      西元年月,
      搭乘次數區間
    )
  ]


  # ==========================================================
  # 建立完整月份 × 分類
  # ==========================================================

  complete_table = CJ(
    西元年月 =
      month_table$西元年月,

    搭乘次數區間 =
      c(
        "僅一次",
        "二至四次",
        "五次以上"
      ),

    unique =
      TRUE
  )


  monthly_group = merge(
    complete_table,
    monthly_group,
    by = c(
      "西元年月",
      "搭乘次數區間"
    ),
    all.x = TRUE
  )


  monthly_group[
    is.na(人數),
    人數 := 0
  ]


  # ==========================================================
  # 加入該月總使用人數
  # ==========================================================

  monthly_group = merge(
    monthly_group,
    monthly_total,
    by = "西元年月",
    all.x = TRUE
  )


  # ==========================================================
  # 比例
  # ==========================================================

  monthly_group[
    ,
    比例 :=
      fifelse(
        !is.na(使用人數) &
        使用人數 > 0,

        人數 /
        使用人數 *
        100,

        NA_real_
      )
  ]


  monthly_group[
    ,
    比例 :=
      round(
        比例,
        1
      )
  ]


  # ==========================================================
  # 人數寬表
  # ==========================================================

  count_table = dcast(
    monthly_group,
    西元年月 ~ 搭乘次數區間,
    value.var = "人數",
    fill = 0
  )


  # ==========================================================
  # 比例寬表
  # ==========================================================

  ratio_table = dcast(
    monthly_group,
    西元年月 ~ 搭乘次數區間,
    value.var = "比例"
  )


  # ==========================================================
  # 改欄位名稱
  # ==========================================================

  setnames(
    count_table,
    old = c(
      "僅一次",
      "二至四次",
      "五次以上"
    ),
    new = c(
      "僅一次_人數",
      "二至四次_人數",
      "五次以上_人數"
    )
  )


  setnames(
    ratio_table,
    old = c(
      "僅一次",
      "二至四次",
      "五次以上"
    ),
    new = c(
      "僅一次_比例",
      "二至四次_比例",
      "五次以上_比例"
    )
  )


  # ==========================================================
  # 合併
  # ==========================================================

  result = merge(
    copy(month_table)[
      ,
      .(
        西元年月,
        月份
      )
    ],
    monthly_total,
    by = "西元年月",
    all.x = TRUE
  )


  result = merge(
    result,
    count_table,
    by = "西元年月",
    all.x = TRUE
  )


  result = merge(
    result,
    ratio_table,
    by = "西元年月",
    all.x = TRUE
  )


  # ==========================================================
  # 沒有乘客的月份補 0
  # ==========================================================

  count_cols = c(
    "使用人數",
    "僅一次_人數",
    "二至四次_人數",
    "五次以上_人數"
  )


  for (col in count_cols) {

    set(
      result,
      i = which(
        is.na(
          result[[col]]
        )
      ),
      j = col,
      value = 0
    )
  }


  # ==========================================================
  # 檢查
  # ==========================================================

  result[
    ,
    分類人數合計 :=
      僅一次_人數 +
      二至四次_人數 +
      五次以上_人數
  ]


  result[
    ,
    人數檢查 :=
      分類人數合計 ==
      使用人數
  ]


  # ==========================================================
  # 欄位順序
  # ==========================================================

  result = result[
    ,
    .(
      月份,

      使用人數,

      僅一次_人數,
      僅一次_比例,

      二至四次_人數,
      二至四次_比例,

      五次以上_人數,
      五次以上_比例,

      分類人數合計,
      人數檢查
    )
  ]


  return(
    list(
      table =
        result,

      person_month =
        person_month,

      detail =
        monthly_group
    )
  )
}


