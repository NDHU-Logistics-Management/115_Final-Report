# ============================================================
# Part B
# 搭乘次數區間月人數變化折線圖
#
# 三條線：
# 僅一次
# 二至四次
# 五次以上
#
# 顏色：
# gray.colors(3, start = 0.3, end = 0.75)
# ============================================================

plot_frequency_count = function(
  data,
  title,
  filename,
  flag = NULL,
  ylab = "人數"
) {

  x = 1:nrow(data)

  y1 = data$僅一次_人數
  y2 = data$二至四次_人數
  y3 = data$五次以上_人數

  # 顏色設定
  color = gray.colors(
    3,
    start = 0.3,
    end = 0.75
  )

  # Y 軸範圍
  ymax = max(
    c(y1, y2, y3),
    na.rm = TRUE
  )

  y_upper = ymax * 1.12

  if (!is.finite(y_upper) || y_upper <= 0) {
    y_upper = 1
  }

  y_ticks = pretty(
    c(0, ymax),
    n = 5
  )

  png(
    filename = file.path(FIG_DIR, filename),
    width = 15,
    height = 5,
    units = "in",
    res = 300
  )

  par(
    family = "msjh",
    mar = c(5, 6, 4, 8),
    mgp = c(3.5, 0.8, 0),
    bty = "l",
    cex.lab = 1.5
  )

  plot(
    x, y1,
    type = "n",
    xlim = c(1, nrow(data)),
    ylim = c(0, y_upper),
    xaxt = "n",
    yaxt = "n",
    xlab = "月份",
    ylab = ylab,
    main = "",
    cex.main = 1.7,
    cex.lab = 1.5
  )

  abline(
    h = y_ticks,
    col = "grey80",
    lty = 3,
    lwd = 0.8
  )

  abline(
    v = x,
    col = "grey90",
    lty = 3,
    lwd = 0.6
  )

  # 三條線都改成圓形
  lines(
    x, y1,
    type = "o",
    pch = 16,
    lty = 1,
    lwd = 1.7,
    cex = 1,
    col = color[1]
  )

  lines(
    x, y2,
    type = "o",
    pch = 16,
    lty = 1,
    lwd = 1.7,
    cex = 1,
    col = color[2]
  )

  lines(
    x, y3,
    type = "o",
    pch = 16,
    lty = 1,
    lwd = 1.7,
    cex = 1,
    col = color[3]
  )

  # [修訂 A1/A2] 業者資料不完整月份（三條線都標）
  flag_points(x, y1, data$月份, flag, cex = 1.3)
  flag_points(x, y2, data$月份, flag, cex = 1.3)
  flag_points(x, y3, data$月份, flag, cex = 1.3)

  # [修訂] 主標題置左
  title(main = title, adj = 0, cex.main = 1.7)

  x_pos = seq(
    1,
    nrow(data),
    by = 2
  )

  axis(
    side = 1,
    at = x_pos,
    labels = data$月份[x_pos],
    las = 1,
    cex.axis = 1.2
  )

  axis(
    side = 2,
    at = y_ticks,
    labels = format(
      y_ticks,
      big.mark = ",",
      scientific = FALSE
    ),
    las = 1,
    cex.axis = 1.2
  )

  legend(
    "topright",
    inset = c(-0.1, 0),
    legend = c("僅一次", "二至四次", "五次以上"),
    col = color,
    pch = c(16, 16, 16),
    lty = c(1, 1, 1),
    lwd = 1.7,
    bty = "n",
    xpd = TRUE,
    cex = 1.25
  )

  dev.off()
}


