# 2. 共用資料整理函數
# ============================================================

prepare_usage_data = function(data) {

  x = copy(
    as.data.table(data)
  )


  # ----------------------------------------------------------
  # 日期
  # ----------------------------------------------------------

  x[
    ,
    `資料代表日期(yyyy-MM-dd)` :=
      as.Date(
        `資料代表日期(yyyy-MM-dd)`
      )
  ]


  # ----------------------------------------------------------
  # 卡號
  # ----------------------------------------------------------

  x[
    ,
    卡號 :=
      trimws(
        as.character(
          卡號
        )
      )
  ]


  # ----------------------------------------------------------
  # 票種
  # ----------------------------------------------------------

  x[
    ,
    票種次類型 :=
      trimws(
        as.character(
          票種次類型
        )
      )
  ]


  # ----------------------------------------------------------
  # 原始票證筆數
  # ----------------------------------------------------------

  x[
    ,
    原始票證筆數 :=
      as.numeric(
        原始票證筆數
      )
  ]


  # ----------------------------------------------------------
  # 日期範圍
  # ----------------------------------------------------------

  x = x[
    `資料代表日期(yyyy-MM-dd)` >=
      start_date &
    `資料代表日期(yyyy-MM-dd)` <=
      end_date
  ]


  # ----------------------------------------------------------
  # 排除無法判定使用者或使用次數的資料
  # ----------------------------------------------------------

  x = x[
    !is.na(卡號) &
    卡號 != "" &
    !is.na(原始票證筆數) &
    原始票證筆數 > 0
  ]


  # ----------------------------------------------------------
  # 西元年月
  # ----------------------------------------------------------

  x[
    ,
    西元年月 :=
      format(
        `資料代表日期(yyyy-MM-dd)`,
        "%Y-%m"
      )
  ]


  return(x)
}


# ============================================================
# Part A
# 1. 平均每日使用次數
#
# 正式定義：
#
# 每人每月使用次數 =
# 該月總使用次數 / 該月使用人數
#
# 平均每日使用次數 =
# 每人每月使用次數 / 該月天數
#
# 因此：
#
# 平均每日使用次數 =
# 該月總使用次數 /
# (該月使用人數 × 該月天數)
#
# 該月總使用次數 =
# 紀錄筆數 .N
#
# 該月使用人數 =
# uniqueN(卡號)
# ============================================================

calculate_avg_daily_use = function(data) {

  x = prepare_usage_data(
    data
  )


  # ==========================================================
  # 每月統計
  # ==========================================================

  monthly = x[
    ,
    .(

      該月總使用次數 = .N,

      該月使用人數 =
        uniqueN(
          卡號
        )

    ),
    by = 西元年月
  ]


  # ==========================================================
  # 補齊所有月份
  # ==========================================================

  result = merge(
    copy(month_table),
    monthly,
    by = "西元年月",
    all.x = TRUE
  )


  # ==========================================================
  # 計算
  # ==========================================================

  result[
    ,
    每人每月使用次數 :=
      fifelse(
        !is.na(該月使用人數) &
        該月使用人數 > 0,

        該月總使用次數 /
        該月使用人數,

        NA_real_
      )
  ]


  result[
    ,
    平均每日使用次數 :=
      fifelse(
        !is.na(每人每月使用次數),

        每人每月使用次數 /
        該月天數,

        NA_real_
      )
  ]


  # ==========================================================
  # 四捨五入
  #
  # 注意：
  # 先使用未四捨五入數值計算平均每日，
  # 最後才四捨五入
  # ==========================================================

  result[
    ,
    `:=`(

      每人每月使用次數 =
        round(
          每人每月使用次數,
          2
        ),

      平均每日使用次數 =
        round(
          平均每日使用次數,
          3
        )
    )
  ]


  # ==========================================================
  # 欄位順序
  # ==========================================================

  result = result[
    ,
    .(
      月份,
      該月天數,
      該月總使用次數,
      該月使用人數,
      每人每月使用次數,
      平均每日使用次數
    )
  ]


  return(result)
}


