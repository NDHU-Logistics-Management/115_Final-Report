# Part D
# 正式表格整理
#
# 移除：
# 分類人數合計
# 人數檢查
#
# 這兩欄只保留在 R 裡做檢查
# ============================================================

clean_frequency_table = function(data) {

  x = copy(
    data
  )


  remove_cols = intersect(
    c(
      "分類人數合計",
      "人數檢查"
    ),
    names(x)
  )


  if (
    length(remove_cols) > 0
  ) {

    x[
      ,
      (remove_cols) := NULL
    ]
  }


  return(x)
}



