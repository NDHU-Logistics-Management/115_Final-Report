# 1. 建立完整月份表
# 113/06 ～ 115/06
# ============================================================

create_month_table = function(
  start_date,
  end_date
) {

  month_date = seq(
    from = as.Date(
      format(
        start_date,
        "%Y-%m-01"
      )
    ),
    to = as.Date(
      format(
        end_date,
        "%Y-%m-01"
      )
    ),
    by = "month"
  )


  result = data.table(
    西元年月 =
      format(
        month_date,
        "%Y-%m"
      ),

    該月天數 =
      days_in_month(
        month_date
      )
  )


  result[
    ,
    月份 :=
      sprintf(
        "%03d/%02d",

        as.integer(
          format(
            month_date,
            "%Y"
          )
        ) - 1911,

        as.integer(
          format(
            month_date,
            "%m"
          )
        )
      )
  ]


  return(result)
}


month_table = create_month_table(
  start_date,
