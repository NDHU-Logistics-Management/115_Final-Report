# Part A
# 平均每日使用次數折線圖
# ============================================================

plot_avg_daily_use = function(
  data,
  title,
  filename,
  flag = NULL,
  ycol = "平均每日使用次數",
  ylab = "平均每日使用次數"
) {

  x = 1:nrow(data)

  y = data[[ycol]]


  # ==========================================================
  # Y 軸範圍
  # ==========================================================

  ymin = floor(
    min(
      y,
      na.rm = TRUE
    ) * 100
  ) / 100


  ymax = ceiling(
    max(
      y,
      na.rm = TRUE
    ) * 100
  ) / 100


  y_range = ymax - ymin


  if (
    !is.finite(y_range) ||
    y_range == 0
  ) {

    y_range = 0.05
  }


  y_lower = max(
    0,
    ymin - y_range * 0.15
  )


  y_upper =
    ymax + y_range * 0.30


  # ==========================================================
  # Y 軸刻度
  # ==========================================================

  y_ticks = pretty(
    c(
      y_lower,
      ymax
    ),
    n = 5
  )

  # [修訂] 軸標籤維持 2 位小數；刻度若細到 2 位小數會重複（如 0.06、0.06），改取較疏的刻度
  if (anyDuplicated(sprintf("%.2f", y_ticks))) {
    y_ticks = pretty(c(y_lower, ymax), n = 3)
  }


  # ==========================================================
  # 開圖
  # ==========================================================

  png(
    filename = file.path(FIG_DIR, filename),
    width = 15,
    height = 5,
    units = "in",
    res = 300
  )


  par(
    family = "msjh",
    mar = c(5, 6, 4, 8),
    mgp = c(3.5, 0.8, 0),
    bty = "l",
    cex.lab = 1.5
  )


  # ==========================================================
  # 主圖
  # ==========================================================

  plot(
    x,
    y,

    type = "n",

    xlim = c(
      1,
      nrow(data) + 0.5
    ),

    ylim = c(
      y_lower,
      y_upper
    ),

    xaxt = "n",
    yaxt = "n",

    xlab = "月份",
    ylab = ylab,

    main = "",
    cex.main = 1.7,
    cex.lab = 1.5
  )


  # ==========================================================
  # 水平網格
  # ==========================================================

  abline(
    h = y_ticks,
    col = "grey80",
    lty = 3,
    lwd = 0.8
  )


  # ==========================================================
  # 垂直網格
  # ==========================================================

  abline(
    v = x,
    col = "grey90",
    lty = 3,
